-- Forward 031 (PdoRepository complements) test schema, PostgreSQL 17. Runs only in a disposable container.
-- aspec_flag.active is SMALLINT (the Adianti flag columns): only BooleanStorage::Integer can compare it.
-- The lifecycle columns are TIMESTAMP(0): the repository stamps whole seconds.
DROP TABLE IF EXISTS aspec_flag;
CREATE TABLE aspec_flag (id INTEGER NOT NULL PRIMARY KEY, active SMALLINT NULL, native BOOLEAN NULL, label VARCHAR(50) NULL);
DROP TABLE IF EXISTS aspec_local_event;
CREATE TABLE aspec_local_event (id INTEGER NOT NULL PRIMARY KEY, happened_at TIMESTAMP(6) NULL, utc_at TIMESTAMP(6) NULL, day DATE NULL);
DROP TABLE IF EXISTS aspec_note;
CREATE TABLE aspec_note (id VARCHAR(26) PRIMARY KEY, title VARCHAR(100) NOT NULL, score INTEGER NOT NULL, created_at TIMESTAMP(0) NULL, updated_at TIMESTAMP(0) NULL, deleted_at TIMESTAMP(0) NULL);
DROP TABLE IF EXISTS aspec_trash_doc;
CREATE TABLE aspec_trash_doc (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(100) NOT NULL, version INTEGER NULL, deleted_at TIMESTAMP(0) NULL, updated_at TIMESTAMP(0) NULL);
DROP TABLE IF EXISTS aspec_sale;
CREATE TABLE aspec_sale (id INTEGER NOT NULL PRIMARY KEY, region VARCHAR(10) NULL, product VARCHAR(20) NULL, qty INTEGER NULL, amount NUMERIC(12,2) NULL, weight DOUBLE PRECISION NULL, sold_on DATE NULL, version INTEGER NULL, updated_at TIMESTAMP(0) NULL, deleted_at TIMESTAMP(0) NULL);
DROP TABLE IF EXISTS aspec_region;
CREATE TABLE aspec_region (code VARCHAR(10) NOT NULL PRIMARY KEY, zone VARCHAR(10) NULL, deleted_at TIMESTAMP(0) NULL);
