        );
        $this->assertEquals(
            ['01-01', '04-21', '05-01', '09-07', '10-12', '11-20'],
            array_map(static fn(array $r): string => sprintf('%02d-%02d', $r['month'], $r['day']), $set->toArray()['recurring']),
            'recurring: true, 1, t, TRUE, y and yes'
        );
        $this->assertTrue($set->isHoliday('2030-04-21') && !$set->isHoliday('2025-04-21'), 'a recurring row repeats from the year of its date');
        $custom = HolidaySet::fromRows([['holiday_date' => '2027-03-10', 'every_year' => 't']], 'holiday_date', 'every_year');
        $this->assertTrue($custom->isHoliday('2028-03-10') && !$custom->isHoliday('2026-03-10'), 'named fields');
        $this->assertEquals(0, HolidaySet::fromRows([])->count());
        foreach ([
            'missing date' => [['recurring' => true]],
            'unreadable flag' => [['date' => '2026-01-01', 'recurring' => 'maybe']],
            'flag 2' => [['date' => '2026-01-01', 'recurring' => 2]],
