    private function testContinuousCalendar(): void
    {
        $calendar = new ContinuousCalendar();
        $ny = new DateTimeZone('America/New_York');
        $a = new DateTimeImmutable('2026-03-07 23:30:00.250000', $ny);
        $this->assertEquals(86400, $calendar->secondsPerDay());
        $this->assertEquals(86400, ContinuousCalendar::SECONDS_PER_DAY);
        $this->assertEquals('2026-03-07T23:30:00.250000-05:00', $calendar->advance($a, 0)?->format(MachineSnapshot::DATE_FORMAT), 'advance(a, 0) = a');
        $this->assertEquals('2026-03-08T00:30:00.250000-05:00', $calendar->advance($a, 3600)?->format(MachineSnapshot::DATE_FORMAT), 'elapsed seconds, in the zone of $from');
        $this->assertEquals('2026-03-08T03:30:00.250000-04:00', $calendar->advance($a, 3 * 3600)?->format(MachineSnapshot::DATE_FORMAT), 'across the daylight-saving change: elapsed hours');
        $this->assertEquals(1, $calendar->workSecondsBetween($a, $a->modify('+1500 milliseconds')), 'floored');
        $this->assertEquals(0, $calendar->workSecondsBetween($a, $a->modify('+999 milliseconds')));
        $this->assertEquals(0, $calendar->workSecondsBetween($a, $a), 'empty interval');
        $this->assertEquals(0, $calendar->workSecondsBetween($a->modify('+1 hour'), $a), 'reversed interval');
        $this->assertEquals(10800, $calendar->workSecondsBetween($a, $a->modify('+3 hours')));
        $this->assertThrows(InvalidArgumentException::class, fn() => $calendar->advance($a, -1));

        // Before the epoch: a negative microsecond count keeps its fraction
        $old = new DateTimeImmutable('1969-12-31T23:59:59.500000Z');
        $this->assertEquals('1969-12-31T23:59:59.500000+00:00', $calendar->advance($old, 0)?->format(MachineSnapshot::DATE_FORMAT));
        $this->assertEquals('1970-01-01T00:00:00.500000+00:00', $calendar->advance($old, 1)?->format(MachineSnapshot::DATE_FORMAT));
        $this->assertEquals(-500000, CalendarTime::micros($old));
        $this->assertEquals('1969-12-31T23:59:58.000000+00:00', CalendarTime::fromMicros(-2_000_000, $old)->format(MachineSnapshot::DATE_FORMAT));
    }

    private function testHolidaySet(): void
    {
        $this->assertCount(0, HolidaySet::none());
        $this->assertEquals(['dates' => [], 'recurring' => []], HolidaySet::none()->toArray());
        $set = new HolidaySet(['2026-02-17', new DateTimeImmutable('2026-02-16T23:00:00-03:00')]);
        $this->assertTrue($set->isHoliday('2026-02-16') && $set->isHoliday('2026-02-17'), 'texts and instants (read in their own zone)');
        $this->assertFalse($set->isHoliday('2026-02-18'));
        $this->assertEquals(['2026-02-16', '2026-02-17'], $set->toArray()['dates'], 'sorted');
        $this->assertTrue($set->contains(new DateTimeImmutable('2026-02-16T01:00:00Z')), 'the date of the instant in its own zone');
        $this->assertFalse($set->contains((new DateTimeImmutable('2026-02-16T01:00:00Z'))->setTimezone(new DateTimeZone('America/Sao_Paulo'))), 'the 15th in Sao Paulo');

        $recurring = HolidaySet::none()->withRecurring(11, 20, 2024);
        $this->assertFalse($recurring->isHoliday('2023-11-20'), 'not before its first year');
        $this->assertTrue($recurring->isHoliday('2024-11-20') && $recurring->isHoliday('2031-11-20'), 'every year from its first year');
        $this->assertFalse($recurring->isHoliday('2024-11-21'));
        $this->assertEquals([['month' => 11, 'day' => 20, 'fromYear' => 2024]], $recurring->toArray()['recurring']);
        $this->assertEquals(2024, $recurring->withRecurring(11, 20, 2026)->toArray()['recurring'][0]['fromYear'], 'the earliest year is kept');
        $this->assertEquals(2024, HolidaySet::none()->withRecurring(11, 20, 2026)->withRecurring(11, 20, 2024)->toArray()['recurring'][0]['fromYear']);
        $leap = HolidaySet::none()->withRecurring(2, 29, 2024);
        $this->assertTrue($leap->isHoliday('2028-02-29'), 'February 29th of a leap year');
        $this->assertEquals(
            [['month' => 1, 'day' => 1, 'fromYear' => 2026], ['month' => 12, 'day' => 25, 'fromYear' => 2020]],
            HolidaySet::none()->withRecurring(12, 25, 2020)->withRecurring(1, 1, 2026)->toArray()['recurring'],
            'recurring days sorted by month and day'
        );
        $this->assertThrows(InvalidArgumentException::class, fn() => HolidaySet::none()->withRecurring(2, 30, 2026));
        $this->assertThrows(InvalidArgumentException::class, fn() => HolidaySet::none()->withRecurring(13, 1, 2026));
        $this->assertThrows(InvalidArgumentException::class, fn() => HolidaySet::none()->withRecurring(0, 1, 2026));
        foreach (['2026-02-30', '2026-2-3', '26-02-03', '2026-02-03 ', '12026-02-03', 'x', ''] as $bad) {
            $this->assertThrows(InvalidArgumentException::class, fn() => new HolidaySet([$bad]), "refused: '{$bad}'");
            $this->assertThrows(InvalidArgumentException::class, fn() => HolidaySet::none()->isHoliday($bad), "refused by isHoliday: '{$bad}'");
        }

        // Immutable: every with*() is a copy
        $base = new HolidaySet(['2026-01-01']);
        $more = $base->withDate('2026-12-25')->withDate('2026-03-01');
        $this->assertFalse($base->isHoliday('2026-12-25'), 'the original is unchanged');
        $this->assertEquals(['2026-01-01', '2026-03-01', '2026-12-25'], $more->toArray()['dates'], 'withDate keeps the dates sorted');
        $this->assertTrue($more->withDate(new DateTimeImmutable('2026-05-01T10:00:00Z'))->isHoliday('2026-05-01'));
        $this->assertEquals(4, $more->withRecurring(4, 21, 2026)->count(), 'dates + recurring days');
        $this->assertFalse($more->isHoliday('2026-04-21'), 'withRecurring() leaves the original unchanged');
        $this->assertEquals(1, $base->withRecurring(4, 21, 2026)->withRecurring(4, 21, 2027)->count() - 1, 'the same recurring day counts once');
    }

    private function testHolidaySetFromRows(): void
    {
        $rows = [
            ['date' => '2026-11-20', 'recurring' => true],
            ['date' => '2026-02-16 00:00:00', 'recurring' => false],
            (object) ['date' => new DateTimeImmutable('2026-04-03T00:00:00-03:00'), 'recurring' => 0],
            ['date' => '2026-01-01', 'recurring' => 1],
            ['date' => '2026-04-21T00:00:00', 'recurring' => 't'],
            ['date' => '2026-05-01', 'recurring' => ' TRUE '],
            ['date' => '2026-09-07', 'recurring' => 'y'],
            ['date' => '2026-10-12', 'recurring' => 'yes'],
            ['date' => '2026-06-04', 'recurring' => 'f'],
            ['date' => '2026-06-05', 'recurring' => 'false'],
            ['date' => '2026-06-08', 'recurring' => 'n'],
            ['date' => '2026-06-09', 'recurring' => 'no'],
            ['date' => '2026-06-10', 'recurring' => '0'],
            ['date' => '2026-06-11', 'recurring' => ''],
            ['date' => '2026-06-12', 'recurring' => null],
            ['date' => '2026-06-15'],
        ];
        $set = HolidaySet::fromRows($rows);
        $this->assertEquals(
            ['2026-02-16', '2026-04-03', '2026-06-04', '2026-06-05', '2026-06-08', '2026-06-09', '2026-06-10', '2026-06-11', '2026-06-12', '2026-06-15'],
