    // ==========================================
    // SLA parity with a reference clock
    // ==========================================

    /**
     * An SLA region (idle → running → met, D-style policy: start on entering `submitted`, met on
     * `approved`, paused while `docs_pending`) driven by random synthetic histories, compared after
     * every step with a reference clock that recomputes the SLA from the history, as the consumer's
     * clock does: elapsed working seconds of every segment outside the pause, due instant where the
     * budget runs out. Two policies at once: 2 business days and 16 working hours.
     */
    private function testSlaParityWithAReferenceClock(): void
    {
        $definition = Spec::machine('quote', 2)
            ->region('progress', 'draft')
                ->state('draft')->on('SUBMIT', 'submitted')
                ->state('submitted')->on('START', 'analysis')
                ->state('analysis')
                    ->on('ASK_DOCS', 'docs_pending')
                    ->on('APPROVE', 'approved')
                ->state('docs_pending')->on('DOCS_SENT', 'analysis')
                ->finalState('approved')
            ->region('sla_days', 'idle')
                ->state('idle')->on('SUBMIT', 'running')
                ->state('running')->deadline('P2D', 'SLA_DAYS_BREACHED', calendar: 'business', pausedWhile: 'progress.docs_pending')
                    ->on('APPROVE', 'met')
                    ->on('SLA_DAYS_BREACHED', 'running')
                ->finalState('met')
            ->region('sla_hours', 'idle')
                ->state('idle')->on('SUBMIT', 'running')
                ->state('running')->deadline('PT16H', 'SLA_HOURS_BREACHED', calendar: 'team', pausedWhile: 'progress.docs_pending')
                    ->on('APPROVE', 'met')
                    ->on('SLA_HOURS_BREACHED', 'running')
                ->finalState('met')
            ->build();
        $machine = new StateMachine(null, self::calendars());
        MachineDefinitionValidator::validate($definition, $machine->getGuardRegistry(), null, $machine->getCalendarRegistry());
        $policies = [
            'sla_days' => ['budget' => 172800, 'spec' => self::tableSpec(['kind' => 'uteis', 'days' => [1, 2, 3, 4, 5], 'start' => '08:00', 'end' => '18:00'])],
            'sla_hours' => ['budget' => 57600, 'spec' => self::tableSpec(['kind' => 'time', 'days' => [1, 2, 3, 4, 5], 'start' => '08:00', 'end' => '18:00'])],
        ];

        mt_srand(4148);
        $compared = ['due' => 0, 'paused' => 0, 'idle' => 0, 'met' => 0];
        $excluded = 0;
        for ($process = 0; $process < 60; $process++) {
            $t = self::randomInstant(new DateTimeZone('America/Sao_Paulo'), false)->getTimestamp();
            $events = ['SUBMIT', 'START'];
            for ($k = mt_rand(0, 3); $k > 0; $k--) {
                $events[] = 'ASK_DOCS';
                $events[] = 'DOCS_SENT';
            }
            $events[] = 'APPROVE';
            $snapshot = $machine->initialSnapshot($definition, null, self::sp($t))->getSnapshot();
            $history = [['draft', $t]];
            $tainted = ['sla_days' => false, 'sla_hours' => false];
            foreach ($policies as $region => $policy) {
                $this->assertFalse(self::referenceClock($history, 'submitted', 'approved', ['docs_pending'], $policy['budget'], $policy['spec'], $t)['started'], "process {$process} {$region}: not started at the opening");
                $this->assertEquals('idle', $snapshot->stateOf($region));
                $compared['idle']++;
            }
            foreach ($events as $type) {
                $t += [mt_rand(60, 7200), mt_rand(3600, 30000), mt_rand(86400, 4 * 86400)][mt_rand(0, 2)];
                $result = $machine->transition($definition, $snapshot, Event::external($type, self::sp($t)));
                $this->assertTrue($result->isAccepted(), "process {$process}: {$type} accepted");
                $snapshot = $result->getSnapshot();
                $history[] = [$snapshot->stateOf('progress'), $t];
                foreach ($policies as $region => $policy) {
                    $clock = self::referenceClock($history, 'submitted', 'approved', ['docs_pending'], $policy['budget'], $policy['spec'], $t);
                    $state = $snapshot->stateOf($region);
                    if ($type === 'ASK_DOCS' && $clock['remaining'] <= 0) {
                        // Declared difference: an overdue SLA paused and resumed is due at the resume
                        // (already overdue); the recomputing clock keeps the first crossing instant.
                        $tainted[$region] = true;
                    }
                    if ($tainted[$region]) {
                        $excluded++;
                        continue;
                    }
                    if ($clock['started'] === false) {
                        $this->assertEquals('idle', $state, "process {$process} {$region}: not started on either side");
                        $compared['idle']++;
                    } elseif ($clock['done']) {
                        $this->assertEquals('met', $state, "process {$process} {$region}: met on both sides");
                        $compared['met']++;
                    } elseif ($clock['paused']) {
                        $this->assertTrue($snapshot->isPaused($region), "process {$process} {$region}: paused on both sides");
                        $this->assertEquals($clock['remaining'], $snapshot->pausedRemaining($region), "process {$process} {$region}: the same balance");
                        $compared['paused']++;
                    } else {
                        $this->assertEquals($clock['due'], $snapshot->dueAt($region)?->getTimestamp(), sprintf('process %d %s after %s: due %s (reference) = %s (library)', $process, $region, $type, date(DATE_ATOM, (int) $clock['due']), $snapshot->dueAt($region)?->format(DATE_ATOM)));
                        $compared['due']++;
                    }
                }
            }
        }
        $this->assertTrue($compared['due'] >= 300 && $compared['paused'] >= 100 && $compared['met'] >= 80 && $compared['idle'] === 120, 'compared: ' . json_encode($compared) . ", excluded: {$excluded}");
