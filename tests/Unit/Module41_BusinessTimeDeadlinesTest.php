     * The code between the markers is block $index of example 14.11, token by token (its `use`
     * lines are imports of this file; a bare expression of the page is kept here as `$rN = ...`).
     */
    private function assertTranscribed(string $name, int $index, int $imports): void
    {
        $source = (string) file_get_contents(__FILE__);
        $start = strpos($source, "// {$name} >>>\n");
        $end = strpos($source, "// <<< {$name}\n");
        $this->assertTrue($start !== false && $end !== false && $end > $start, "transcription {$name} marked");
        $tokens = ReadmeBlocks::codeTokens(substr($source, (int) $start, (int) $end - (int) $start));
        $transcribed = [];
        for ($i = 0, $n = count($tokens); $i < $n; $i++) {
            if (preg_match('/^\$r\d+$/', $tokens[$i]) === 1 && ($tokens[$i + 1] ?? null) === '=') {
                $i++;
                continue;
            }
            $transcribed[] = $tokens[$i];
        }
        $block = ReadmeBlocks::of(dirname(__DIR__, 2) . '/docs/en/state-machine/business-time.md', '14.11')[$index] ?? '';
        preg_match_all('/^use ([^;]+);$/m', $block, $uses);
