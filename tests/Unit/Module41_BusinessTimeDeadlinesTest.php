    /**
     * The description of a calendar of the table, with the holidays the consumer's clock counts.
     *
     * @param array<string, mixed> $calendar
     * @return array<string, mixed>
     */
    private static function tableSpec(array $calendar): array
    {
        $dates = [];
        $recurring = [];
        foreach (self::cases()['holidayRows'] as $row) {
            if ($row['scope'] !== 'nacional' || !$row['active'] || $row['deleted']) {
                continue;
            }
            if ($row['recurring']) {
                $recurring[substr($row['date'], 5)] = (int) substr($row['date'], 0, 4);
            } else {
                $dates[$row['date']] = true;
            }
        }
        $minutes = static fn(string $hm): int => (int) substr($hm, 0, 2) * 3600 + (int) substr($hm, 3, 2) * 60;

        return [
            'kind' => $calendar['kind'],
            'tz' => new DateTimeZone('America/Sao_Paulo'),
            'dates' => $dates,
            'recurring' => $recurring,
            'days' => $calendar['kind'] === 'uteis' ? [1, 2, 3, 4, 5] : $calendar['days'],
            'start' => $calendar['kind'] === 'uteis' ? 0 : $minutes($calendar['start']),
            'end' => $calendar['kind'] === 'uteis' ? 86400 : $minutes($calendar['end']),
        ];
    }

    // ------------------------------------------
    // The reference clock: one window per local date, integer timestamps, written apart from the
    // library in the style of the consumer's SLA clock (a day starts at its local midnight, the next
    // day is "+1 day" of the wall clock; a window is [start, end] of the day or nothing).
    // ------------------------------------------

    /**
     * @param array<string, mixed> $spec
     * @return array{0: int, 1: int}|null
     */
    private static function referenceWindow(string $date, array $spec): ?array
    {
        $day = new \DateTime($date . ' 00:00:00', $spec['tz']);
        if (!in_array((int) $day->format('N'), $spec['days'], true)) {
            return null;
        }
        $from = $spec['recurring'][substr($date, 5)] ?? null;
        if (isset($spec['dates'][$date]) || ($from !== null && (int) substr($date, 0, 4) >= $from)) {
            return null;
        }
        $at = static function (int $seconds) use ($date, $spec): int {
            $moment = new \DateTime($date . ' 00:00:00', $spec['tz']);
            if ($seconds >= 86400) {
                $moment->modify('+1 day');
                $seconds -= 86400;
            }
            $moment->setTime(intdiv($seconds, 3600), intdiv($seconds % 3600, 60), $seconds % 60);

            return $moment->getTimestamp();
        };

        return [$at($spec['start']), $at($spec['end'])];
    }

    /** @param array<string, mixed> $spec */
    private static function referenceDayOf(int $timestamp, array $spec): string
    {
        return (new \DateTime('@' . $timestamp))->setTimezone($spec['tz'])->format('Y-m-d');
    }

    /** @param array<string, mixed> $spec */
    private static function referenceNextDay(string $date, array $spec): string
    {
        return (new \DateTime($date . ' 00:00:00', $spec['tz']))->modify('+1 day')->format('Y-m-d');
    }

    /** @param array<string, mixed> $spec */
    private static function referenceWorkSeconds(int $from, int $to, array $spec): int
    {
        if ($to <= $from) {
            return 0;
        }
        $total = 0;
        $date = self::referenceDayOf($from, $spec);
        for ($i = 0; (new \DateTime($date . ' 00:00:00', $spec['tz']))->getTimestamp() < $to && $i < 3700; $i++) {
            $window = self::referenceWindow($date, $spec);
            if ($window !== null) {
                $total += max(0, min($to, $window[1]) - max($from, $window[0]));
            }
            $date = self::referenceNextDay($date, $spec);
        }

        return $total;
    }

    /** @param array<string, mixed> $spec */
    private static function referenceAdvance(int $from, int $seconds, array $spec): ?int
    {
        if ($seconds <= 0) {
            return $from;
        }
        $date = self::referenceDayOf($from, $spec);
        for ($i = 0; $i < 3700; $i++) {
            $window = self::referenceWindow($date, $spec);
            if ($window !== null) {
                $start = max($from, $window[0]);
                if ($start < $window[1]) {
                    if ($seconds <= $window[1] - $start) {
                        return $start + $seconds;
                    }
                    $seconds -= $window[1] - $start;
                }
            }
            $date = self::referenceNextDay($date, $spec);
        }

        return null;
    }

    /**
     * The SLA recomputed from the history at $now: started on the last entry into $startState, met on
     * the first arrival at $doneState after it, paused inside the $pause states.
     *
     * @param list<array{0: string, 1: int}> $history State entered and instant, in order
     * @param list<string> $pause
     * @param array<string, mixed> $spec
     * @return array{started: bool, done: bool, paused: bool, remaining: int, due: int|null}
     */
    private static function referenceClock(array $history, string $startState, string $doneState, array $pause, int $budget, array $spec, int $now): array
    {
        $n = count($history);
        $startIndex = null;
        for ($i = $n - 1; $i >= 0; $i--) {
            if ($history[$i][0] === $startState) {
                $startIndex = $i;
                break;
            }
        }
        if ($startIndex === null) {
            return ['started' => false, 'done' => false, 'paused' => false, 'remaining' => $budget, 'due' => null];
        }
        $doneIndex = null;
        for ($j = $startIndex + 1; $j < $n; $j++) {
            if ($history[$j][0] === $doneState) {
                $doneIndex = $j;
                break;
            }
        }
        $end = $doneIndex !== null ? $history[$doneIndex][1] : $now;
        $last = $doneIndex !== null ? $doneIndex - 1 : $n - 1;
        $spent = 0;
        $due = null;
        for ($k = $startIndex; $k <= $last; $k++) {
            $segmentStart = $history[$k][1];
            $segmentEnd = min($k + 1 < $n ? $history[$k + 1][1] : $end, $end);
            if ($segmentEnd <= $segmentStart || in_array($history[$k][0], $pause, true)) {
                continue;
            }
            $work = self::referenceWorkSeconds($segmentStart, $segmentEnd, $spec);
            if ($due === null && $spent + $work >= $budget) {
                $due = self::referenceAdvance($segmentStart, $budget - $spent, $spec);
            }
            $spent += $work;
        }
        $remaining = $budget - $spent;
        $paused = $doneIndex === null && in_array($history[$n - 1][0], $pause, true);
        if ($due === null && !$paused) {
            $due = self::referenceAdvance($now, $remaining, $spec);
        }

        return ['started' => true, 'done' => $doneIndex !== null, 'paused' => $paused, 'remaining' => $remaining, 'due' => $due];
    }
