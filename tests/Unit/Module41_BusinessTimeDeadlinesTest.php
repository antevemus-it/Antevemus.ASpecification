            'integer date' => [['date' => 20260101]],
            'bad date' => [['date' => '2026-13-01']],
            'text before the date' => [['date' => 'on 2026-01-01']],
            'not a row' => ['2026-01-01'],
        ] as $case => $bad) {
            $this->assertThrows(InvalidArgumentException::class, fn() => HolidaySet::fromRows($bad), "fromRows refuses: {$case}");
        }
    }

    private function testCalendarConstruction(): void
    {
        $tz = new DateTimeZone('UTC');
        $none = HolidaySet::none();
        foreach ([[0], [8], ['6'], [6.0], [null]] as $weekend) {
            $this->assertThrows(InvalidArgumentException::class, fn() => new BusinessDayCalendar($tz, $none, $weekend), 'weekend ' . json_encode($weekend));
        }
        $this->assertThrows(InvalidArgumentException::class, fn() => new BusinessDayCalendar($tz, $none, [6, 7], 0), 'a limit of 0 days');
        $this->assertEquals(86400, (new BusinessDayCalendar($tz, $none, [7, 6, 6], 1))->secondsPerDay(), 'repeated weekdays, a limit of one day');
        $this->assertEquals(3700, AbstractWindowCalendar::DEFAULT_MAX_DAYS);

        $hours = static fn(array $days, string $start, string $end, int $max = 3700) => new WorkingHoursCalendar($tz, $days, $start, $end, $none, $max);
        $this->assertThrows(InvalidArgumentException::class, fn() => $hours([], '08:00', '18:00'), 'no working day');
        $this->assertThrows(InvalidArgumentException::class, fn() => $hours([1, 9], '08:00', '18:00'), 'weekday 9');
        $this->assertThrows(InvalidArgumentException::class, fn() => $hours([1], '08:00', '18:00', 0), 'a limit of 0 days');
        foreach (['8:00', '08:60', '08:00:60', '24:01', '24:00:01', '23:60', '25:00', '30:00', '08h00', '', '08:00:00:00', ' 08:00'] as $bad) {
            $this->assertThrows(InvalidArgumentException::class, fn() => $hours([1], $bad, '23:00'), "start '{$bad}'");
        }
        $this->assertThrows(InvalidArgumentException::class, fn() => $hours([1], '10:00', '10:00'), 'empty window');
        $this->assertThrows(InvalidArgumentException::class, fn() => $hours([1], '10:00', '09:59'), 'reversed window');
        $this->assertEquals(36000, $hours([1, 2, 3, 4, 5], '08:00', '18:00')->secondsPerDay());
        $this->assertEquals(3600, $hours([1], '23:00', '24:00')->secondsPerDay(), '24:00 is the end of the date');
        $this->assertEquals(86400, $hours([1], '00:00', '24:00:00')->secondsPerDay());
        $this->assertEquals(35970, $hours([1], '08:00:30', '18:00')->secondsPerDay(), 'HH:MM:SS');
        $this->assertEquals(36059, $hours([1], '08:00', '18:00:59')->secondsPerDay());
        $this->assertEquals(1, $hours([7, 7], '00:00', '00:00:01', 1)->secondsPerDay(), 'one second, repeated weekdays, a limit of one day');
        $this->assertEquals(60, $hours([1], '08:59', '09:00')->secondsPerDay(), 'minute 59');
        $this->assertEquals(86399, $hours([1], '00:00', '23:59:59')->secondsPerDay(), 'second 59');
    }

    private function testBusinessDayCalendar(): void
    {
        $sp = new DateTimeZone('America/Sao_Paulo');
        $calendar = new BusinessDayCalendar($sp, self::nationalHolidays());
        $friday = new DateTimeImmutable('2026-02-13T17:00:00-03:00');
        $this->assertEquals('2026-02-18T17:00:00-03:00', $calendar->advance($friday, 86400)?->format(DATE_ATOM), 'one business day: the weekend and Carnival skipped');
        $this->assertEquals(86400, $calendar->workSecondsBetween($friday, new DateTimeImmutable('2026-02-18T17:00:00-03:00')));
        $this->assertEquals('2026-02-20T00:00:00-03:00', $calendar->advance(new DateTimeImmutable('2026-02-14T10:00:00-03:00'), 2 * 86400)?->format(DATE_ATOM), 'from a Saturday: Wednesday and Thursday whole, due at the end of Thursday');
        $this->assertEquals('2026-03-07T00:00:00-03:00', $calendar->advance(new DateTimeImmutable('2026-03-06T00:00:00-03:00'), 86400)?->format(DATE_ATOM), 'exactly the window left: the end of the window');
        $this->assertEquals('2026-02-13T17:00:00-03:00', $calendar->advance($friday, 0)?->format(DATE_ATOM), 'zero balance: the start itself');
        $saturday = new DateTimeImmutable('2026-02-14T10:00:00-03:00');
        $this->assertEquals('2026-02-14T10:00:00-03:00', $calendar->advance($saturday, 0)?->format(DATE_ATOM), 'zero balance off the calendar: the start itself');
        $this->assertEquals(0, $calendar->workSecondsBetween($saturday, new DateTimeImmutable('2026-02-18T00:00:00-03:00')), 'Saturday to Wednesday: nothing counts');
        $this->assertEquals('2026-02-18T00:00:01-03:00', $calendar->advance($saturday, 1)?->format(DATE_ATOM), 'the first second after the weekend and Carnival');
        $this->assertEquals('+00:00', $calendar->advance($friday->setTimezone(new DateTimeZone('UTC')), 3600)?->format('P'), 'the result keeps the zone of $from');
        $this->assertThrows(InvalidArgumentException::class, fn() => $calendar->advance($friday, -1));

        // Another weekend (Friday and Saturday off) and no weekend at all
        $gulf = new BusinessDayCalendar($sp, HolidaySet::none(), [5, 6]);
        $this->assertEquals('2026-03-08T12:00:00-03:00', $gulf->advance(new DateTimeImmutable('2026-03-05T12:00:00-03:00'), 86400)?->format(DATE_ATOM), 'Thursday noon + 1 day: Sunday noon');
        $always = new BusinessDayCalendar($sp, HolidaySet::none(), []);
        $this->assertEquals('2026-03-08T12:00:00-03:00', $always->advance(new DateTimeImmutable('2026-03-07T12:00:00-03:00'), 86400)?->format(DATE_ATOM), 'no weekend: Saturday counts');

        // The limit of days walked: advance() gives up (null), workSecondsBetween() counts what it walked
        $from = new DateTimeImmutable('2026-03-06T00:00:00-03:00'); // a Friday
        $five = new BusinessDayCalendar($sp, HolidaySet::none(), [6, 7], 5);
        $four = new BusinessDayCalendar($sp, HolidaySet::none(), [6, 7], 4);
        $this->assertEquals('2026-03-11T00:00:00-03:00', $five->advance($from, 3 * 86400)?->format(DATE_ATOM), 'Friday, Monday and Tuesday within five dates');
        $this->assertTrue($four->advance($from, 3 * 86400) === null, 'not within four dates');
        $this->assertEquals(2 * 86400, $four->workSecondsBetween($from, new DateTimeImmutable('2026-03-20T00:00:00-03:00')), 'counted over four dates only');
        $this->assertEquals(10 * 86400, $calendar->workSecondsBetween($from, new DateTimeImmutable('2026-03-20T00:00:00-03:00')), 'the default limit: two weeks');
        $this->assertTrue($calendar->advance($from, 2700 * 86400) === null, '2 700 business days are beyond 3 700 dates');
        $this->assertTrue($calendar->advance($from, 2500 * 86400) !== null, '2 500 are not');
    }

    private function testWorkingHoursCalendar(): void
    {
        $sp = new DateTimeZone('America/Sao_Paulo');
        $team = new WorkingHoursCalendar($sp, [1, 2, 3, 4, 5], '08:00', '18:00', self::nationalHolidays());
        $friday = new DateTimeImmutable('2026-02-13T17:00:00-03:00');
        $this->assertEquals('2026-02-18T09:00:00-03:00', $team->advance($friday, 7200)?->format(DATE_ATOM), 'two working hours: 17:00 to 18:00, then Wednesday 08:00 to 09:00');
        $this->assertEquals(7200, $team->workSecondsBetween($friday, new DateTimeImmutable('2026-02-18T09:00:00-03:00')));
        $this->assertEquals('2026-03-02T09:00:00-03:00', $team->advance(new DateTimeImmutable('2026-03-02T07:00:00-03:00'), 3600)?->format(DATE_ATOM), 'before the window');
        $this->assertEquals('2026-03-06T09:00:00-03:00', $team->advance(new DateTimeImmutable('2026-03-05T19:00:00-03:00'), 3600)?->format(DATE_ATOM), 'after the window');
        $this->assertEquals('2026-03-02T18:00:00-03:00', $team->advance(new DateTimeImmutable('2026-03-02T08:00:00-03:00'), 36000)?->format(DATE_ATOM), 'a whole window ends at its end');
        $this->assertEquals(36000, $team->workSecondsBetween(new DateTimeImmutable('2026-03-02T07:00:00-03:00'), new DateTimeImmutable('2026-03-02T20:00:00-03:00')));
        $this->assertEquals(0, $team->workSecondsBetween(new DateTimeImmutable('2026-03-07T00:00:00-03:00'), new DateTimeImmutable('2026-03-09T08:00:00-03:00')), 'a weekend and the early hours of Monday');

        $odd = new WorkingHoursCalendar($sp, [1, 2, 3, 4, 5], '08:59:59', '17:00:01', HolidaySet::none());
        $this->assertEquals(28802, $odd->secondsPerDay());
        $this->assertEquals('2026-03-02T09:00:00-03:00', $odd->advance(new DateTimeImmutable('2026-03-02T07:00:00-03:00'), 1)?->format(DATE_ATOM), 'a window starting at 08:59:59');
        $this->assertEquals('2026-03-02T17:00:01-03:00', $odd->advance(new DateTimeImmutable('2026-03-02T17:00:00-03:00'), 1)?->format(DATE_ATOM), 'a window ending at 17:00:01');
        $this->assertEquals('2026-03-03T09:00:00-03:00', $odd->advance(new DateTimeImmutable('2026-03-02T17:00:00-03:00'), 2)?->format(DATE_ATOM), 'then the next one');
        $this->assertEquals(
            32399,
            $team->workSecondsBetween(new DateTimeImmutable('2026-03-02 09:00:00.000001', $sp), new DateTimeImmutable('2026-03-03T07:00:00-03:00')),
            'a microsecond short of 9 hours, and a next day whose window has not started: floored, nothing added'
        );

        $saturdays = new WorkingHoursCalendar($sp, [1, 2, 3, 4, 5, 6], '09:00', '13:30', HolidaySet::none());
        $this->assertEquals(16200, $saturdays->secondsPerDay());
        $this->assertEquals('2026-03-07T10:00:00-03:00', $saturdays->advance(new DateTimeImmutable('2026-03-06T13:00:00-03:00'), 5400)?->format(DATE_ATOM), 'Saturday counts for this team');

        $night = new WorkingHoursCalendar($sp, [1, 2, 3, 4, 5, 6, 7], '22:00', '24:00', HolidaySet::none());
