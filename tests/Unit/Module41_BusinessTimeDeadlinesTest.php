    private function testCalendarProperties(): void
    {
        mt_srand(4146);
        $zones = ['America/Sao_Paulo', 'America/New_York', 'UTC', 'Europe/Lisbon', 'Australia/Lord_Howe'];
        $checks = 0;
        for ($iteration = 0; $iteration < 160; $iteration++) {
            $tz = new DateTimeZone($zones[mt_rand(0, count($zones) - 1)]);
            [$calendar, $spec] = self::randomCalendar($tz);
            $a = self::randomInstant($tz, mt_rand(0, 1) === 1);
            $s1 = mt_rand(0, 3) === 0 ? mt_rand(0, 3600) : mt_rand(0, 12 * 86400);
            $s2 = $s1 + mt_rand(0, 6 * 86400);
            $label = sprintf('#%d %s %s from %s', $iteration, $spec['kind'], $tz->getName(), $a->format(MachineSnapshot::DATE_FORMAT));

            $this->assertEquals($a->format(MachineSnapshot::DATE_FORMAT), $calendar->advance($a, 0)?->format(MachineSnapshot::DATE_FORMAT), "{$label}: advance(a, 0) = a");
            $d1 = $calendar->advance($a, $s1);
            $d2 = $calendar->advance($a, $s2);
            $this->assertTrue($d1 !== null && $d2 !== null, "{$label}: within the limit");
            \assert($d1 !== null && $d2 !== null);
            $this->assertTrue(CalendarTime::micros($d1) <= CalendarTime::micros($d2), "{$label}: advance is monotonic in the balance");
            $this->assertEquals($s1, $calendar->workSecondsBetween($a, $d1), "{$label}: workSecondsBetween(a, advance(a, s1)) = s1");
            $this->assertEquals($s2, $calendar->workSecondsBetween($a, $d2), "{$label}: workSecondsBetween(a, advance(a, s2)) = s2");
            $this->assertEquals($s2 - $s1, $calendar->workSecondsBetween($d1, $d2), "{$label}: the balance between the two");
            if ($s1 > 0) {
                $this->assertEquals(1, $calendar->workSecondsBetween(CalendarTime::fromMicros(CalendarTime::micros($d1) - CalendarTime::MICROS, $d1), $d1), "{$label}: the last second spent is a working second");
            }

            // Monotonic and additive in the end of the interval, bounded by the elapsed time
            $b = $a->modify('+' . mt_rand(0, 9 * 86400) . ' seconds');
            $c = $b->modify('+' . mt_rand(0, 9 * 86400) . ' seconds');
            $ab = $calendar->workSecondsBetween($a, $b);
            $ac = $calendar->workSecondsBetween($a, $c);
            $this->assertTrue($ab <= $ac, "{$label}: monotonic in the end");
            $this->assertTrue($ac <= $c->getTimestamp() - $a->getTimestamp() + 1, "{$label}: never more than the elapsed time");
            $whole = $a->setTime((int) $a->format('H'), (int) $a->format('i'), (int) $a->format('s'));
            $wb = $whole->modify('+' . mt_rand(0, 9 * 86400) . ' seconds');
            $wc = $wb->modify('+' . mt_rand(0, 9 * 86400) . ' seconds');
            $this->assertEquals($calendar->workSecondsBetween($whole, $wc), $calendar->workSecondsBetween($whole, $wb) + $calendar->workSecondsBetween($wb, $wc), "{$label}: additive on whole seconds");

            // The reference (one window per local date, integer timestamps) agrees on whole seconds
            $this->assertEquals(self::referenceWorkSeconds($whole->getTimestamp(), $wc->getTimestamp(), $spec), $calendar->workSecondsBetween($whole, $wc), "{$label}: workSecondsBetween = the reference");
            $reference = self::referenceAdvance($whole->getTimestamp(), $s1, $spec);
            $this->assertEquals($reference, $calendar->advance($whole, $s1)?->getTimestamp(), "{$label}: advance = the reference");

            // An off date never counts, nor the hours outside a window
            for ($probe = 0; $probe < 40; $probe++) {
                $date = $a->modify("+{$probe} days")->setTimezone($tz)->format('Y-m-d');
                $start = new DateTimeImmutable("{$date} 00:00:00", $tz);
                $end = new DateTimeImmutable("{$date} 00:00:00", $tz);
                $end = $end->modify('+1 day');
                if (self::referenceWindow($date, $spec) === null) {
                    $this->assertEquals(0, $calendar->workSecondsBetween($start, $end), "{$label}: {$date} is off, nothing counts");
                    break;
                }
            }
            $checks++;
        }
        $this->assertEquals(160, $checks);
    }

