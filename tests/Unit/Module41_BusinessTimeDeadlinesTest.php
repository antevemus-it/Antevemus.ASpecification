    /**
     * Replays the table with the library's calendars; mismatches per "zone calendar function" group.
     *
     * @param array<string, mixed> $data
     * @return array<string, list<string>>
     */
    private static function replayCases(array $data, HolidaySet $holidays): array
    {
        $mismatches = [];
        $calendars = [];
        foreach ($data['cases'] as [$zone, $name, $function, $from, $argument, $expected]) {
            $tz = new DateTimeZone($zone);
            $calendar = $calendars["{$zone} {$name}"] ??= self::tableCalendar($data['calendars'][$name], $tz, $holidays);
            $start = (new DateTimeImmutable($from))->setTimezone($tz);
            $actual = $function === 'advance'
                ? $calendar->advance($start, $argument)?->format('c')
                : $calendar->workSecondsBetween($start, new DateTimeImmutable($argument));
            $group = "{$zone} {$name} {$function}";
            $mismatches[$group] ??= [];
            if ($actual !== $expected) {
                $mismatches[$group][] = sprintf('%s %s: expected %s, got %s', $from, json_encode($argument), json_encode($expected), json_encode($actual));
            }
        }

        return $mismatches;
    }

