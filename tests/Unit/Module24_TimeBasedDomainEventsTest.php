    // PDO: reference DDL and parity
    // ==========================================

    private function testReferenceDdl(): void
    {
        $ddl = (string) file_get_contents(self::DDL);
        $this->assertTrue(str_contains($ddl, 'CREATE TABLE IF NOT EXISTS domain_event_trigger_state'));
        $this->assertTrue(str_contains($ddl, 'PRIMARY KEY (trigger_name, entity_class, entity_id)'));

        // A 1.11.0 database gets the new table by running the script again; its outbox is untouched
        $pdo = new PDO('sqlite::memory:', options: [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $outboxOnly = substr($ddl, 0, (int) strpos($ddl, '-- domain_event_trigger_state (since 1.12.0)'));
        self::loadDdl($pdo, $outboxOnly);
        $old = new PdoDomainEventOutbox($pdo);
        $old->enqueue([new DomainEventOutboxEntry('01AAAAAAAAAAAAAAAAAAAAAAAA', new DomainEvent('e', 't', DomainEventKind::ENTER, 'C', '1', $this->day(1)))]);
        $this->assertThrows(PDOException::class, fn() => $pdo->query('SELECT COUNT(*) FROM domain_event_trigger_state'));
        self::loadDdl($pdo, $ddl);
        self::loadDdl($pdo, $ddl);   // idempotent
        $this->assertEquals(1, $old->count(), 'the outbox rows survive');
        $columns = array_map(static fn(array $c): string => (string) $c['name'], $pdo->query('PRAGMA table_info(domain_event_trigger_state)')->fetchAll(PDO::FETCH_ASSOC));
        $this->assertEquals(PdoTriggerStateStore::COLUMNS, $columns);

        // Constraints: the primary key is the second barrier; CHECKs on satisfied and version
        $store = new PdoTriggerStateStore($pdo);
        $this->assertTrue($store->compareAndSet('t', 'C', '1', null, true, $this->day(1)));
        $this->assertThrows(PDOException::class, fn() => $pdo->exec("INSERT INTO domain_event_trigger_state VALUES ('t', 'C', '1', 0, '2026-01-01 09:00:00.000000', 1)"));
        $this->assertThrows(PDOException::class, fn() => $pdo->exec("INSERT INTO domain_event_trigger_state VALUES ('t', 'C', '2', 2, '2026-01-01 09:00:00.000000', 1)"));
        $this->assertThrows(PDOException::class, fn() => $pdo->exec("INSERT INTO domain_event_trigger_state VALUES ('t', 'C', '3', 1, '2026-01-01 09:00:00.000000', 0)"));
        $row = $pdo->query('SELECT satisfied, evaluated_at, version FROM domain_event_trigger_state')->fetch(PDO::FETCH_ASSOC);
        $this->assertEquals(['1', '2026-01-01 09:00:00.000000', '1'], array_map('strval', array_values((array) $row)));

        // Identifiers validated; a schema qualifies the table; driver errors with the SQLSTATE
        $this->assertThrows(InvalidArgumentException::class, fn() => new PdoTriggerStateStore($pdo, 'bad table'));
        $this->assertThrows(InvalidArgumentException::class, fn() => new PdoTriggerStateStore($pdo, schema: 'bad;schema'));
        $this->assertEquals('main.domain_event_trigger_state', (new PdoTriggerStateStore($pdo, schema: 'main'))->getTable());
        $this->assertEquals(1, (new PdoTriggerStateStore($pdo, schema: 'main'))->count());
        $this->assertTrue($store->getPdo() === $pdo);
        $missing = $this->assertThrows(DomainEventPersistenceException::class, fn() => (new PdoTriggerStateStore($pdo, 'no_such_table'))->count());
        $this->assertTrue($missing instanceof DomainEventPersistenceException && $missing->getSqlState() !== null);
        $pdo->exec("UPDATE domain_event_trigger_state SET evaluated_at = 'not a date'");
        $this->assertThrows(DomainEventPersistenceException::class, fn() => $store->find('t', 'C', '1'));
        // A failed INSERT that is not a race propagates (CHECK on a hand-made table)
        $pdo->exec('CREATE TABLE narrow_state (trigger_name VARCHAR(120) NOT NULL, entity_class VARCHAR(255) NOT NULL, entity_id VARCHAR(190) NOT NULL, satisfied SMALLINT NOT NULL CHECK (satisfied = 0), evaluated_at VARCHAR(26) NOT NULL, version INTEGER NOT NULL, PRIMARY KEY (trigger_name, entity_class, entity_id))');
        $narrow = new PdoTriggerStateStore($pdo, 'narrow_state');
        $this->assertTrue($narrow->compareAndSet('t', 'C', '1', null, false, $this->day(1)));
        $this->assertFalse($narrow->compareAndSet('t', 'C', '1', null, true, $this->day(1)), 'present: lost, not an error');
        $this->assertThrows(DomainEventPersistenceException::class, fn() => $narrow->compareAndSet('t', 'C', '2', null, true, $this->day(1)), 'an integrity error without a concurrent row is not a lost race: it propagates');
    }

    /** The same operations give the same rows in memory and in SQLite. */
    private function testStateStoreParityInMemoryVsPdo(): void
    {
        $results = [];
        foreach ($this->stores() as $label => $factory) {
            $store = $factory();
            $store->compareAndSet('t', 'C', 'x', null, true, $this->day(1));
            $store->compareAndSet('t', 'C', 'x', 1, false, $this->day(2));
            $store->compareAndSet('t', 'C', 'y', null, true, new DateTimeImmutable('2026-01-03 10:11:12.345678', new DateTimeZone('UTC')));
            $store->compareAndSet('t', 'C', 'z', null, true, $this->day(4));
            $store->compareAndDelete('t', 'C', 'z', 1);
            $results[$label] = [
                array_map(static fn(TriggerState $s): array => $s->toArray(), array_values($store->findMany('t', 'C', ['x', 'y', 'z']))),
                array_map(static fn(TriggerState $s): array => $s->toArray(), $store->findSatisfied('t', 'C', 10)),
