    private function testTimedTriggerDefinition(): void
    {
        $timed = $this->overdue();
        $this->assertTrue($timed->isTimed());
        $this->assertTrue($timed->hasCrossingInstant());
        $this->assertFalse($this->paidTrigger()->isTimed());
        $this->assertFalse($this->paidTrigger()->hasCrossingInstant());
        $this->assertEquals('collection.started', $timed->eventFor(DomainEventKind::ENTER));
        $this->assertEquals('collection.ended', $timed->eventFor(DomainEventKind::EXIT));

        // The specification is rebuilt with the instant it is given
        $bill = $this->bill('B-1', 5);
        $this->assertFalse($timed->specificationAt($this->day(35, '00:00:00'))->isSatisfiedBy($bill), 'exactly 30 days: not more than 30');
        $this->assertTrue($timed->specificationAt($this->day(35, '00:00:01'))->isSatisfiedBy($bill));
        $this->assertTrue($timed->specificationAt($this->day(36))->isSatisfiedBy($bill));

        // The public specification of a time-based trigger refuses to answer without an instant
        $this->assertThrows(LogicException::class, fn() => $timed->getSpecification()->isSatisfiedBy($bill));
        $this->assertThrows(LogicException::class, fn() => $timed->specification->isSatisfiedBy($bill));
        // A plain trigger answers specificationAt() with its fixed specification
        $paid = $this->paidTrigger();
        $this->assertTrue($paid->specificationAt($this->day(1)) === $paid->specification);

        // The factory must return a specification; the calculator an instant or null
        $broken = SpecificationTrigger::timed('broken', static fn(): string => 'nope', onEnter: 'x');
        $this->assertThrows(UnexpectedValueException::class, fn() => $broken->specificationAt($this->day(1)));
        $badClock = SpecificationTrigger::timed('bad.clock', static fn(): ISpecification => Spec::alwaysTrue(), onEnter: 'x', crossedAt: static fn(): string => 'yesterday');
        $this->assertThrows(UnexpectedValueException::class, fn() => $badClock->crossingInstant($bill, $this->day(1), DomainEventKind::ENTER));
        $this->assertEquals(null, $paid->crossingInstant($bill, $this->day(1), DomainEventKind::ENTER));
        $this->assertEquals('2026-02-04', $timed->crossingInstant($bill, $this->day(40), DomainEventKind::ENTER)?->format('Y-m-d'));
        // The kind is the third argument (a calculator declaring fewer parameters ignores it)
        $byKind = SpecificationTrigger::timed('by.kind', static fn(): ISpecification => Spec::alwaysTrue(), onEnter: 'x',
            crossedAt: static fn(object $e, DateTimeImmutable $now, DomainEventKind $kind): ?DateTimeImmutable => $kind === DomainEventKind::EXIT ? null : $now);
        $this->assertEquals(null, $byKind->crossingInstant($bill, $this->day(1), DomainEventKind::EXIT));

        // Same name rules as a plain trigger
        $this->assertThrows(InvalidArgumentException::class, fn() => SpecificationTrigger::timed('no.events', static fn(): ISpecification => Spec::alwaysTrue()));
        $this->assertThrows(InvalidArgumentException::class, fn() => SpecificationTrigger::timed(' padded', static fn(): ISpecification => Spec::alwaysTrue(), 'a'));

        // The set lists its time-based triggers
        $set = new TriggerSet($this->paidTrigger(), $timed);
        $this->assertTrue($set->hasTimed());
        $this->assertEquals(['bill.overdue'], array_map(static fn(SpecificationTrigger $t): string => $t->name, $set->timedTriggers()));
        $this->assertFalse((new TriggerSet($this->paidTrigger()))->hasTimed());
        $this->assertEquals([], (new TriggerSet($this->paidTrigger()))->timedTriggers());
    }

    private function testEvaluatorBuildsTheTimedSpecificationWithNow(): void
    {
        $set = new TriggerSet($this->overdue());
        $bill = $this->bill('B-1', 5);
        $evaluator = new TriggerEvaluator();

        // The same object crosses only because the instant moved: before at day 20, after at day 36
        $this->assertFalse($evaluator->statesOf($set, $bill, $this->day(20))->isSatisfied('bill.overdue'));
        $this->assertTrue($evaluator->statesOf($set, $bill, $this->day(36))->isSatisfied('bill.overdue'));
        $this->assertTrue($evaluator->satisfies($this->overdue(), $bill, $this->day(36)));
        $this->assertThrows(LogicException::class, fn() => $evaluator->satisfies($this->overdue(), $bill));

        // changes(): both sides evaluated with the $now it receives (creation that already satisfies = enter)
        $changes = $evaluator->changes($set, null, $bill, $this->day(36));
        $this->assertEquals(['collection.started'], $changes->eventNames());
        $this->assertEquals('2026-02-05 09:00', $changes->getEvents()[0]->occurredAt->format('Y-m-d H:i'), 'a write stamps its own instant');
        $this->assertCount(0, $evaluator->changes($set, null, $bill, $this->day(20)));

        // Without an instant a time-based trigger is an evaluation error, never a silent false
        $states = $evaluator->statesOf($set, $bill);
        $this->assertTrue($states->errorOf('bill.overdue') instanceof LogicException);
        $failed = $evaluator->changes($set, null, $bill);
        $this->assertCount(0, $failed);
        $this->assertTrue($failed->hasErrors());
        $this->assertEquals(TriggerEvaluationError::SIDE_AFTER, $failed->getErrors()[0]->side);

        // With a clock and no $now, the clock gives the instant of the evaluation too
        $clocked = new TriggerEvaluator(fn(): DateTimeImmutable => $this->day(36));
        $this->assertEquals(['collection.started'], $clocked->changes($set, null, $bill)->eventNames());
        $this->assertCount(0, (new TriggerEvaluator(fn(): DateTimeImmutable => $this->day(20)))->changes($set, null, $bill));

        // A factory that throws is that trigger's evaluation error; the others are still evaluated
        $exploding = SpecificationTrigger::timed('exploding', static fn(): ISpecification => throw new RuntimeException('factory down'), onEnter: 'never');
        $mixed = $evaluator->changes(new TriggerSet($exploding, $this->overdue()), null, $bill, $this->day(36));
        $this->assertEquals(['collection.started'], $mixed->eventNames());
        $this->assertEquals('exploding', $mixed->getErrors()[0]->triggerName);
    }

    // ==========================================
    // D2: the state store contract (InMemory and PDO)
    // ==========================================

    /**
     * @param Closure(): ITriggerStateStore $factory
     */
    private function testStateStoreContract(string $label, Closure $factory): void
    {
        $store = $factory();
        $at = $this->day(1);
        $this->assertEquals(null, $store->find('t', 'C', '1'), "{$label}: empty");
        $this->assertTrue($store->compareAndSet('t', 'C', '1', null, false, $at), "{$label}: insert");
        $this->assertFalse($store->compareAndSet('t', 'C', '1', null, true, $at), "{$label}: insert of an existing row loses");
        $row = $store->find('t', 'C', '1');
        $this->assertEquals(['trigger' => 't', 'entity_class' => 'C', 'entity_id' => '1', 'satisfied' => false, 'evaluated_at' => '2026-01-01 09:00:00.000000', 'version' => 1], $row?->toArray());
        $this->assertFalse($store->compareAndSet('t', 'C', '1', 2, true, $this->day(2)), "{$label}: stale version loses");
        $this->assertEquals(1, $store->find('t', 'C', '1')?->version, "{$label}: a lost write changes nothing");
        $this->assertTrue($store->compareAndSet('t', 'C', '1', 1, true, $this->day(2)), "{$label}: version read wins");
        $this->assertEquals([true, 2, '2026-01-02'], [$store->find('t', 'C', '1')?->satisfied, $store->find('t', 'C', '1')?->version, $store->find('t', 'C', '1')?->evaluatedAt->format('Y-m-d')]);
        $this->assertFalse($store->compareAndSet('t', 'C', '1', 1, false, $this->day(3)), "{$label}: the same version twice: the second loses");

        // An instant in another time zone is stored in UTC
        $this->assertTrue($store->compareAndSet('t', 'C', '9', null, false, new DateTimeImmutable('2026-01-01 06:00:00', new DateTimeZone('America/Sao_Paulo'))));
        $this->assertEquals('2026-01-01 09:00:00.000000', $store->find('t', 'C', '9')?->toArray()['evaluated_at']);
        $this->assertTrue($store->compareAndDelete('t', 'C', '9', 1));

        foreach (['10', '2', 'abc', 'B'] as $id) {
            $this->assertTrue($store->compareAndSet('t', 'C', $id, null, true, $at));
        }
        $this->assertTrue($store->compareAndSet('t', 'C', 'off', null, false, $at));
