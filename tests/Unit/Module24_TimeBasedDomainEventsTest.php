        $report = (new TriggerSweeper($repo, TimedEvents24Bill::class, $set, new InMemoryTriggerStateStore(), $publisher, errors: $reporter))->sweep($this->day(60));
        $this->assertEquals(['collection.started'], $report->eventNames());
