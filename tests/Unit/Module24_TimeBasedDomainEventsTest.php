        $this->assertEquals('Trigger "exploding" could not be swept on ' . TimedEvents24Bill::class . '.', $report->getErrors()[0]->getMessage());
        $this->assertEquals($report->getErrors(), $reporter->errors, 'every error goes to the reporter too');

        // Two concrete classes in one repository: the other class is reported, never keyed under the wrong one
        $reporter = new TimedEvents24RecordingReporter();
        $other = new TimedEvents24OtherBill('O-1', $this->day(1, '00:00:00'));
