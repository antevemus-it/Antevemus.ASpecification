        }
        $this->assertEquals($results['InMemory'], $results['PDO'], 'D2: InMemory = PDO');
        $this->assertEquals('2026-01-03 10:11:12.345678', $results['PDO'][1][0]['evaluated_at'], 'microseconds kept');
    }

    // ==========================================
    // RN-03: two concurrent sweepers over one SQLite store
    // ==========================================

    private function testRn03ConcurrentSweepersOverSqlite(): void
    {
        foreach (['states recorded (compare-and-set on the version)' => true, 'no state yet (insert race, primary key)' => false] as $label => $baseline) {
            $file = (string) tempnam(sys_get_temp_dir(), 'aspec_sweep_');
            try {
                // No crossing instant calculator: A and B stamp their own instants, so the two events
                // of one crossing would have different keys; the outbox's UNIQUE key cannot save
                // them, only the compare-and-set can
                $triggers = new TriggerSet($this->overdue(calculator: false));
                $setup = $this->sqlite('sqlite:' . $file);
                $seed = $this->pdoWorld($setup, $triggers);
                foreach (['B-1' => 5, 'B-2' => 6, 'B-3' => 4, 'B-4' => 90] as $number => $due) {
                    $seed->repository->put($this->bill($number, $due));
                }
                if ($baseline) {
                    $seed->sweeper->baseline($this->day(1));
                }

                $connect = static function () use ($file): PDO {
                    $pdo = new PDO('sqlite:' . $file);
                    $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
                    $pdo->setAttribute(PDO::ATTR_TIMEOUT, 2);

                    return $pdo;
                };
                $a = $this->pdoWorld($pdoA = $connect(), $triggers, $racing = new TimedEvents24RacingStore(new PdoTriggerStateStore($pdoA)));
                $b = $this->pdoWorld($connect(), $triggers);
                $reportB = null;
                // B (another process) runs its whole sweep, one second later, between A's reads and A's first write
                $racing->arm(function () use ($b, &$reportB): void {
                    $reportB = $b->sweeper->sweep($this->day(36, '09:00:01'));
                });
                $reportA = $a->sweeper->sweep($this->day(36));

                $this->assertEquals(3, $reportB?->enteredCount(), "RN-03 ({$label}): B recorded the three crossings");
                $this->assertEquals([0, 3], [$reportA->enteredCount(), $reportA->conflictCount()], "RN-03 ({$label}): A lost every compare-and-set and published nothing");
                $this->assertEquals(3, (new PdoDomainEventOutbox($setup))->count(), "RN-03 ({$label}): one outbox row per crossing");
                foreach (['B-1', 'B-2', 'B-3'] as $id) {
                    $this->assertCount(1, (new PdoDomainEventOutbox($setup))->findByEntity(TimedEvents24Bill::class, $id));
                }
                // Both again, now in the other order: nothing left
                $this->assertEquals(0, $a->sweeper->sweep($this->day(36, '09:00:02'))->enteredCount());
                $this->assertEquals(0, $b->sweeper->sweep($this->day(36, '09:00:03'))->enteredCount());
                $this->assertEquals(3, (new PdoDomainEventOutbox($setup))->count());
                unset($a, $b, $seed, $setup, $pdoA, $racing);
            } finally {
                @unlink($file);
            }
        }
    }

    // ==========================================
    // RN-04: scale (10 000 entities, PdoRepository on SQLite)
    // ==========================================

    private function testRn04Scale(): void
    {
        $measures = [];
        foreach ([1000, 10000] as $rows) {
            $pdo = new PdoRecordingPdo('sqlite::memory:');
            $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
            self::loadDdl($pdo, (string) file_get_contents(self::DDL));
            $pdo->exec('CREATE TABLE aspec_timed_invoice (id INTEGER PRIMARY KEY AUTOINCREMENT, due_date TEXT NOT NULL, paid INTEGER NOT NULL)');
            $transactions = new PdoTransactionManager($pdo);
            $repository = new PdoCountingRepository($pdo, EntityMapping::fromAttributes(TimedEvents24Invoice::class), $transactions);
            // Half of the invoices are overdue on day 60 (due days 1..29), 1 % more cross by day 61 (due day 30)
            $invoices = [];
            for ($i = 0; $i < $rows; $i++) {
                $due = $i % 2 === 0 ? 1 + ($i % 29) : ($i % 100 === 1 ? 31 : 200);
                $invoices[] = new TimedEvents24Invoice($this->day($due, '00:00:00'));
            }
            $repository->putAll($invoices);
            unset($invoices);
            $set = new TriggerSet(SpecificationTrigger::timed(
                'invoice.overdue',
                static fn(DateTimeImmutable $now): ISpecification => Spec::property('paid', Spec::isFalse())->and(Spec::property('dueDate', Spec::lessThan($now->modify('-30 days')))),
                onEnter: 'collection.started',
                onExit: 'collection.ended'
            ));
            $states = new PdoTriggerStateStore($pdo);
            $outbox = new PdoDomainEventOutbox($pdo);
            $sweeper = new TriggerSweeper($repository, TimedEvents24Invoice::class, $set, $states, new OutboxDomainEventPublisher($outbox), $transactions);

            gc_collect_cycles();
            $t = microtime(true);
            $baseline = $sweeper->baseline($this->day(60));
            $baselineMs = (microtime(true) - $t) * 1000;
            $inside = intdiv($rows, 2);
            $this->assertEquals([$rows, 0], [$baseline->recordedCount(), $outbox->count()], "RN-05 ({$rows}): every invoice recorded, nothing published");

            // The sweep that finds no crossing: no entity built, a handful of statements, constant memory
            $repository->hydrations = 0;
            $pdo->reset();
            gc_collect_cycles();
            $base = memory_get_usage();
            memory_reset_peak_usage();
            $t = microtime(true);
            $quiet = $sweeper->sweep($this->day(60, '10:00:00'));
            $quietMs = (microtime(true) - $t) * 1000;
            $quietPeak = memory_get_peak_usage() - $base;
            $this->assertEquals([0, 0], [$quiet->enteredCount(), $quiet->exitedCount()], "RN-04 ({$rows}): no crossing");
            $this->assertEquals(0, $repository->hydrations, "RN-04 ({$rows}): the sweep without crossings builds no entity");
            $pages = intdiv($inside + TriggerSweeper::DEFAULT_BATCH_SIZE - 1, TriggerSweeper::DEFAULT_BATCH_SIZE);
            $this->assertCount(2 * $pages + 2, $pdo->statements, "RN-04 ({$rows}): one state page and one COUNT per {$pages} pages, the empty page, the final COUNT");
            $this->assertEquals($inside, $quiet->statesRead());

            // Day 61: 1 % of the invoices cross. Entities built = the candidates of the query + one re-read per crossing
            $crossing = count(array_filter(range(0, $rows - 1), static fn(int $i): bool => $i % 2 === 1 && $i % 100 === 1));
            $repository->hydrations = 0;
            $pdo->reset();
            gc_collect_cycles();
            $base = memory_get_usage();
            memory_reset_peak_usage();
            $t = microtime(true);
            $busy = $sweeper->sweep($this->day(61, '10:00:00'));
            $busyMs = (microtime(true) - $t) * 1000;
            $busyPeak = memory_get_peak_usage() - $base;
            $this->assertEquals($crossing, $busy->enteredCount(), "RN-04 ({$rows}): the new crossings");
            $this->assertEquals($inside + $crossing + $crossing, $repository->hydrations, "RN-04 ({$rows}): candidates of the query plus one re-read per crossing");
            $this->assertEquals($repository->hydrations, $busy->entitiesLoaded());
            $this->assertEquals($crossing, $outbox->count());

            $measures[$rows] = compact('baselineMs', 'quietMs', 'quietPeak', 'busyMs', 'busyPeak', 'crossing', 'inside') + ['statements' => count($pdo->statements), 'hydrations' => $repository->hydrations];
        }
        // Constant memory: ten times the rows, not ten times the memory
        // (the peak is one page of 500 states and its IN list, whatever the table size)
        $this->assertTrue($measures[10000]['quietPeak'] < 2 * 1024 * 1024, sprintf('RN-04: quiet sweep peak +%d bytes', $measures[10000]['quietPeak']));
        $this->assertTrue($measures[10000]['busyPeak'] < 3 * 1024 * 1024, sprintf('RN-04: busy sweep peak +%d bytes', $measures[10000]['busyPeak']));
        $this->assertTrue($measures[10000]['quietPeak'] < 2 * max($measures[1000]['quietPeak'], 64 * 1024), 'RN-04: the quiet sweep does not grow with the table');
        $this->assertTrue($measures[10000]['busyPeak'] < 2 * max($measures[1000]['busyPeak'], 64 * 1024), 'RN-04: nor the sweep with crossings');

        foreach ($measures as $rows => $m) {
            fwrite(STDOUT, sprintf(
                "    [RN-04] SQLite, %d linhas (%d dentro): baseline %.0f ms; varredura sem travessia %.1f ms, 0 entidades, pico +%.1f KB; varredura com %d travessias %.0f ms, %d entidades (candidatos + releituras), pico +%.1f KB\n",
                $rows,
                $m['inside'],
                $m['baselineMs'],
                $m['quietMs'],
                $m['quietPeak'] / 1024,
                $m['crossing'],
                $m['busyMs'],
                $m['hydrations'],
                $m['busyPeak'] / 1024
            ));
        }
    }

