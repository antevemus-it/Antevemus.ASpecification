        $stores = ['InMemory' => static fn(): ITriggerStateStore => new InMemoryTriggerStateStore()];
        if (extension_loaded('pdo_sqlite')) {
            $stores['PDO'] = fn(): ITriggerStateStore => new PdoTriggerStateStore($this->sqlite());
        }

        return $stores;
    }

    /**
     * Events of the outbox for one entity, as [name, kind, occurred_at].
     *
     * @return list<array{0: string, 1: string, 2: string}>
     */
    private function eventsOf(IDomainEventOutbox $outbox, string $entityId, string $class = TimedEvents24Bill::class): array
    {
        return array_map(
            static fn(DomainEventOutboxEntry $e): array => [$e->event->name, $e->event->kind->value, $e->event->occurredAt->format('Y-m-d H:i')],
            $outbox->findByEntity($class, $entityId)
        );
    }

