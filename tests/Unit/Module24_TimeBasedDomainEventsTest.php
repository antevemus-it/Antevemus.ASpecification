    // ==========================================
    // A crossing is atomic: state and event together
    // ==========================================

    private function testCrossingIsAtomic(): void
    {
        $states = new InMemoryTriggerStateStore();
        $outbox = new InMemoryDomainEventOutbox();
        $transactions = new InMemoryTransactionManager([$states, $outbox]);
        $repo = new InMemoryRepository([$this->bill('B-1', 1)]);
        $set = new TriggerSet($this->overdue());
        $failing = new TriggerSweeper($repo, TimedEvents24Bill::class, $set, $states, new TimedEvents24FailingPublisher(), $transactions);
        $this->assertThrows(RuntimeException::class, fn() => $failing->sweep($this->day(60)), 'a failure of the publisher propagates');
        $this->assertEquals(0, $states->count(), 'the state of the crossing was rolled back with it');
        $working = new TriggerSweeper($repo, TimedEvents24Bill::class, $set, $states, new OutboxDomainEventPublisher($outbox), $transactions);
        $this->assertEquals(1, $working->sweep($this->day(60))->enteredCount(), 'so the next sweep publishes it');
        $this->assertEquals(1, $outbox->count());

        if (!extension_loaded('pdo_sqlite')) {
            return;
        }
        // PDO: the outbox INSERT fails (table gone), the state UPDATE is rolled back
        $pdo = $this->sqlite();
        $w = $this->pdoWorld($pdo);
        $w->bills->put($this->bill('B-1', 1));
        $pdo->exec('DROP TABLE domain_event_outbox');
        $this->assertThrows(DomainEventPersistenceException::class, fn() => $w->sweeper->sweep($this->day(60)));
        $this->assertEquals([false, 1], [$w->states->find('bill.overdue', TimedEvents24Bill::class, 'B-1')?->satisfied, $w->states->find('bill.overdue', TimedEvents24Bill::class, 'B-1')?->version]);
        $this->assertFalse($pdo->inTransaction());
    }

