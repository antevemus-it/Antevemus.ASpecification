/**
 * TimedEvents24RacingStore - State store decorator that runs a hook right before its first write,
 * so that another sweeper (or a write) records the same crossing between this one's read and its
 * compare-and-set (RN-03, D6).
 *
 * @version 1.12.0
 */
final class TimedEvents24RacingStore implements ITriggerStateStore
{
    public int $writes = 0;

    public function __construct(private readonly ITriggerStateStore $inner, private ?Closure $beforeFirstWrite = null)
    {
    }

    public function arm(Closure $hook): void
    {
        $this->beforeFirstWrite = $hook;
    }

    private function race(): void
    {
        $this->writes++;
        if ($this->beforeFirstWrite !== null) {
            $hook = $this->beforeFirstWrite;
            $this->beforeFirstWrite = null;
            $hook();
        }
    }

    public function find(string $triggerName, string $entityClass, string $entityId): ?TriggerState
    {
        return $this->inner->find($triggerName, $entityClass, $entityId);
    }

    public function findByEntity(string $entityClass, string $entityId): array
    {
        return $this->inner->findByEntity($entityClass, $entityId);
    }

    public function findMany(string $triggerName, string $entityClass, array $entityIds): array
    {
        return $this->inner->findMany($triggerName, $entityClass, $entityIds);
    }

    public function findSatisfied(string $triggerName, string $entityClass, int $limit, ?string $afterEntityId = null): array
    {
        return $this->inner->findSatisfied($triggerName, $entityClass, $limit, $afterEntityId);
    }

    public function compareAndSet(string $triggerName, string $entityClass, string $entityId, ?int $expectedVersion, bool $satisfied, DateTimeImmutable $evaluatedAt): bool
    {
        $this->race();

        return $this->inner->compareAndSet($triggerName, $entityClass, $entityId, $expectedVersion, $satisfied, $evaluatedAt);
    }

    public function compareAndDelete(string $triggerName, string $entityClass, string $entityId, int $expectedVersion): bool
    {
        $this->race();

        return $this->inner->compareAndDelete($triggerName, $entityClass, $entityId, $expectedVersion);
    }

    public function count(): int
    {
        return $this->inner->count();
    }
}

