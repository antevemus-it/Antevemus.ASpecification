    /** Day $n of 2026 (day 1 = 2026-01-01), UTC. */
    private function day(int $n, string $time = '09:00:00'): DateTimeImmutable
    {
        return (new DateTimeImmutable('2026-01-01 ' . $time, new DateTimeZone('UTC')))->modify('+' . ($n - 1) . ' days');
    }

    /**
     * "Unpaid and due more than 30 days ago"; the real crossing is the due date + 30 days (without
     * the calculator, every crossing is stamped with the sweep instant).
     */
    private function overdue(string $name = 'bill.overdue', bool $calculator = true): SpecificationTrigger
    {
        return SpecificationTrigger::timed(
            $name,
            static fn(DateTimeImmutable $now): ISpecification => Spec::property('paid', Spec::isFalse())
                ->and(Spec::property('dueDate', Spec::lessThan($now->modify('-30 days')))),
            onEnter: 'collection.started',
            onExit: 'collection.ended',
            crossedAt: $calculator ? static fn(TimedEvents24Bill $bill): DateTimeImmutable => $bill->dueDate->modify('+30 days') : null
        );
    }

    private function paidTrigger(): SpecificationTrigger
    {
        return new SpecificationTrigger('bill.paid', Spec::property('paid', Spec::isTrue()), onEnter: 'bill.settled');
    }

    private function bill(string $number, int $dueDay, bool $paid = false): TimedEvents24Bill
    {
        $bill = new TimedEvents24Bill($number, $this->day($dueDay, '00:00:00'));
        $bill->paid = $paid;

        return $bill;
    }

    /**
     * In-memory wiring.
     *
     * @param list<TimedEvents24Bill> $bills Stored before the decorator exists
     */
    private function inMemoryWorld(?TriggerSet $triggers = null, array $bills = [], ?ITriggerStateStore $states = null, ?IDomainEventOutbox $outbox = null): TimedEvents24World
    {
        $triggers ??= new TriggerSet($this->overdue());
        $repository = new InMemoryRepository($bills);
        $states ??= new InMemoryTriggerStateStore();
        $outbox ??= new InMemoryDomainEventOutbox();
        $clock = new TimedEvents24Clock($this->day(1));
        $publisher = new OutboxDomainEventPublisher($outbox);

        return new TimedEvents24World(
            $repository,
            new TriggeringRepository($repository, $triggers, $publisher, clock: $clock->closure(), states: $states),
            new TriggerSweeper($repository, TimedEvents24Bill::class, $triggers, $states, $publisher),
            $outbox,
            $states,
            $clock,
            $triggers
        );
    }

    /** PDO wiring: repository, state store and outbox on one connection and one transaction manager. */
    private function pdoWorld(PDO $pdo, ?TriggerSet $triggers = null, ?ITriggerStateStore $states = null): TimedEvents24World
    {
        $triggers ??= new TriggerSet($this->overdue());
        $transactions = new PdoTransactionManager($pdo);
        $repository = PdoRepository::forEntity($pdo, TimedEvents24Bill::class, $transactions);
        $states ??= new PdoTriggerStateStore($pdo);
        $outbox = new PdoDomainEventOutbox($pdo);
        $clock = new TimedEvents24Clock($this->day(1));
        $publisher = new OutboxDomainEventPublisher($outbox);

        return new TimedEvents24World(
            $repository,
            new TriggeringRepository($repository, $triggers, $publisher, $transactions, clock: $clock->closure(), states: $states),
            new TriggerSweeper($repository, TimedEvents24Bill::class, $triggers, $states, $publisher, $transactions),
            $outbox,
            $states,
            $clock,
            $triggers
        );
    }

    private function sqlite(string $dsn = 'sqlite::memory:'): PDO
    {
        $pdo = new PDO($dsn);
        $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
        self::loadDdl($pdo, (string) file_get_contents(self::DDL));
        $pdo->exec(self::BILL_TABLE);

        return $pdo;
    }

    /**
     * Runs a DDL script: drops `--` comment lines and executes each `;`-terminated statement.
     */
    private static function loadDdl(PDO $pdo, string $ddl): void
    {
        $lines = array_filter(explode("\n", $ddl), static fn(string $line): bool => !str_starts_with(ltrim($line), '--'));
        foreach (explode(';', implode("\n", $lines)) as $statement) {
            if (trim($statement) !== '') {
                $pdo->exec($statement);
            }
        }
    }

    /**
     * State store backends: label => factory.
