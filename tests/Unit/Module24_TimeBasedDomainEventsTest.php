        $plainOnly = new TriggerSweeper(new InMemoryRepository([$this->bill('B-1', 1, true)]), TimedEvents24Bill::class, new TriggerSet($this->paidTrigger()), new InMemoryTriggerStateStore(), new InMemoryDomainEventPublisher());
