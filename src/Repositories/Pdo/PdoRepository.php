/**
 * PdoRepository - IRepository over a Relational Table through PDO
 *
 * The Domian HibernateRepository of the library (roadmap milestone 21, forward 028): a query is a
 * specification compiled to SQL by the SqlQueryVisitor (any of its dialects), a write is a prepared
 * INSERT/UPDATE/DELETE, a read streams the cursor. The entity is mapped to the table by its author
 * (EntityMapping, by attributes or explicitly).
 *
 * Reads (D7):
 * - find*() builds the entities; iterate*() is a generator over the cursor (constant memory: one row
 *   and one entity at a time; the query runs on the first pull); both order by the identifier, so
 *   time-ordered and generated identifiers come back in insertion order, as from InMemoryRepository
 * - count*() is `SELECT COUNT(*)` and builds no entity; findSingle() asks for at most two rows
 *   (`LIMIT 2` in the dialect) in one query and throws RuntimeException when there is more than one
 * - findPage() paginates through ISqlPagination; only the mapped columns are selected
 * - a specification that cannot be translated raises the visitor's exception; nothing is filtered in
 *   memory unless withInMemoryFallback() was called (then the table is scanned and the specification
 *   evaluated in PHP: only for small tables)
 *
 * Writes (D6), each in a transaction of the ITransactionManager (joining an open one):
 * - put() inserts when the entity has no identifier yet (generated by the IdStrategy) or its row does
 *   not exist, and updates otherwise; update() does the same (the contract's upsert, as in memory);
 *   updateWithDelta() applies the delta to the entity, then update() (AbstractRepository)
 * - putAll() writes every entity in ONE transaction: all or nothing
 * - remove() deletes by identifier; removeAll*() is one compiled `DELETE ... WHERE`
 * - optimistic locking with a #[Version] counter: INSERT writes 1, UPDATE increments it and only
 *   matches the version the entity carries; a stale update or removal throws OptimisticLockException
 *   and writes nothing
 *
 * Every value goes through a prepared parameter; table and column names come only from the mapping,
 * validated as identifiers and quoted by the dialect (RN-04). Driver errors surface as
 * PdoRepositoryException whatever the error mode of the connection, which is left untouched.
 *
 * Out of v1 (D9): relationships and joins, DDL generation, second-level cache, partitions
 * (isNativelyPartitioned() is false; makePartition() throws PartitioningNotSupportedException).
 *
 * MySQL streams only with unbuffered queries (PDO::MYSQL_ATTR_USE_BUFFERED_QUERY = false on the
 * connection); with the default buffered mode the driver holds the whole result before the first row.
 *
 * @template T of IEntity
 * @extends AbstractRepository<T>
 * @version    1.11.0
 * @package    Antevemus\ASpecification
 * @subpackage Repositories\Pdo
 * @author     Heliton Junior (CTO) - <contato@antevemus.com.br>
 * @copyright  Copyright (c) 2025-2026 Antevemus Soluções Inovadoras em TI Ltda.
 * @license    MIT
 */
class PdoRepository extends AbstractRepository
{
    private const DELETE_CHUNK = 500;

    private readonly ISqlDialect $dialect;

    private readonly string $family;

    private readonly ITransactionManager $transactions;

    private readonly PdoValueConverter $converter;

    /** @var list<ColumnMapping> Mapped columns in SELECT order */
    private readonly array $columnList;

    private readonly string $tableSql;

    private readonly string $selectSql;

    private readonly ColumnMapping $idColumn;

    private bool $inMemoryFallback = false;

    private static ?ReflectionProperty $timeOfCreation = null;

    /**
     * @param PDO $pdo Connection to the database holding the table (its attributes are left untouched)
     * @param EntityMapping $mapping Complete mapping (table and identifier)
     * @param ITransactionManager|null $transactions Transaction boundary of the writes; default: a
     *                                               PdoTransactionManager over the same connection
     * @param ISqlDialect|SqlDialect|string|null $dialect SQL dialect; default: deduced from the PDO driver
     * @param ISynchronizer|null $synchronizer In-process synchronizer (NullSynchronizer when null)
     * @throws EntityMappingException When the mapping has no table or no identifier
     */
    public function __construct(
        private readonly PDO $pdo,
        private readonly EntityMapping $mapping,
        ?ITransactionManager $transactions = null,
        ISqlDialect|SqlDialect|string|null $dialect = null,
        ?ISynchronizer $synchronizer = null
    ) {
        $mapping->assertComplete();

        $this->dialect = SqlDialectFactory::create(
            $dialect ?? SqlDialect::fromDriver((string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME))
        );
        $this->family = $this->dialect->getFamily();
        $this->transactions = $transactions ?? new PdoTransactionManager($pdo);
        $this->converter = new PdoValueConverter($this->family);
        $this->columnList = array_values($mapping->getColumns());
        $this->idColumn = $mapping->getId();
        $this->tableSql = $this->dialect->escapeIdentifier((string) $mapping->getTable());
        $this->selectSql = 'SELECT ' . implode(', ', array_map(
            fn(ColumnMapping $c): string => $this->dialect->escapeIdentifier($c->column),
            $this->columnList
        )) . ' FROM ' . $this->tableSql;

        if ($synchronizer !== null) {
            $this->setSynchronizer($synchronizer);
        }
    }

    /**
     * Repository of an entity class mapped with attributes (EntityMapping::fromAttributes()).
     *
     * @param PDO $pdo Connection
     * @param class-string<IEntity> $entityClass Entity class carrying #[Table], #[Id] and #[Column]
     * @param ITransactionManager|null $transactions Transaction boundary (default: over the same connection)
     * @param ISqlDialect|SqlDialect|string|null $dialect SQL dialect (default: from the driver)
     * @return static
     */
    public static function forEntity(
        PDO $pdo,
        string $entityClass,
        ?ITransactionManager $transactions = null,
        ISqlDialect|SqlDialect|string|null $dialect = null
    ): static {
        return new static($pdo, EntityMapping::fromAttributes($entityClass), $transactions, $dialect);
    }

    ///////////////////////////////////////////////////////////////////////////
    // Configuration
    ///////////////////////////////////////////////////////////////////////////

    /**
     * Allows (or forbids again) evaluating in PHP a specification that cannot be translated to SQL:
     * the whole table is read and filtered row by row. Off by default, because loading a table in
     * silence is the worst performance defect a repository can have; turn it on only for small tables.
     *
     * @return static
     */
    public function withInMemoryFallback(bool $enabled = true): static
    {
        $this->inMemoryFallback = $enabled;

        return $this;
    }

    /** True when non-translatable specifications are evaluated in PHP over a full scan. */
    public function hasInMemoryFallback(): bool
    {
        return $this->inMemoryFallback;
    }

    /** The mapping in use. */
    public function getMapping(): EntityMapping
    {
        return $this->mapping;
    }

    /** The connection. */
    public function getConnection(): PDO
    {
        return $this->pdo;
    }

    /** The SQL dialect in use. */
    public function getDialect(): ISqlDialect
    {
        return $this->dialect;
    }

    /** The transaction boundary of the writes. */
    public function getTransactionManager(): ITransactionManager
    {
        return $this->transactions;
    }

    /**
     * The WHERE clause a specification compiles to over this mapping (diagnostics, custom statements).
     *
     * @throws NonTranslatableSpecificationException When the specification cannot be translated
     * @throws UnsupportedSqlOperationException When the dialect lacks an operation the specification needs
     */
    public function toWhereClause(ISpecification $specification): ISqlWhereClause
    {
        return $this->compiler()->translate($specification);
    }

    ///////////////////////////////////////////////////////////////////////////
    // Reads
    ///////////////////////////////////////////////////////////////////////////

    /** {@inheritdoc} */
    public function countAllEntitiesSpecifiedBy(ISpecification $specification): int
    {
        $this->validateSpecification($specification);

        return $this->readConcurrently(function () use ($specification): int {
            $where = $this->compileOrFallback($specification);
            if ($where === null) {
                $count = 0;
                foreach ($this->stream(null, $specification) as $_) {
                    $count++;
                }
                return $count;
            }

            $statement = $this->run('SELECT COUNT(*) FROM ' . $this->tableSql . $this->whereSql($where), $where->getParameters());
            $count = $statement->fetchColumn();
            $statement->closeCursor();

            return (int) $count;
        });
    }

    /** {@inheritdoc} */
    public function iterateAllEntitiesSpecifiedBy(ISpecification $specification): iterable
    {
        $this->validateSpecification($specification);

        // Compiled now, so that a non-translatable specification fails at the call, not at the first pull
        return $this->readConcurrently(function () use ($specification): Generator {
            $where = $this->compileOrFallback($specification);

            return $this->stream($where, $where === null ? $specification : null);
        });
    }

    /** {@inheritdoc} */
    public function findAllEntitiesSpecifiedBy(ISpecification $specification): array
    {
        $this->validateSpecification($specification);

        return $this->readConcurrently(function () use ($specification): array {
            $where = $this->compileOrFallback($specification);

            return iterator_to_array($this->stream($where, $where === null ? $specification : null), false);
        });
    }

    /**
     * {@inheritdoc}
     *
     * One query asking for at most two rows.
     */
    public function findSingleEntitySpecifiedBy(ISpecification $specification): ?IEntity
    {
        $this->validateSpecification($specification);

        return $this->readConcurrently(function () use ($specification): ?IEntity {
            $where = $this->compileOrFallback($specification);
            $limit = ($where !== null && $this->dialect instanceof ISqlPagination) ? 2 : null;

            $found = [];
            foreach ($this->stream($where, $where === null ? $specification : null, $limit, null, []) as $entity) {
                $found[] = $entity;
                if (count($found) > 1) {
                    throw new RuntimeException('Expected a single entity result, but found at least 2');
                }
            }

            return $found[0] ?? null;
        });
    }

    /**
     * One page of the entities satisfying the specification, ordered.
     *
     * @param ISpecification $specification Filter
     * @param int $limit Maximum number of entities (>= 1)
     * @param int $offset Number of entities skipped (>= 0)
     * @param array<string, string> $orderBy Property => 'ASC'|'DESC' (default: the identifier ascending);
     *                                       the identifier is always appended as the last key, so pages
     *                                       never overlap
     * @return array<T>
     * @throws InvalidArgumentException When the limit, the offset, a property or a direction is invalid
     * @throws UnsupportedSqlOperationException When the dialect cannot paginate (not an ISqlPagination)
     */
    public function findPage(ISpecification $specification, int $limit, int $offset = 0, array $orderBy = []): array
    {
        $this->validateSpecification($specification);
        if ($limit < 1) {
            throw new InvalidArgumentException("The page size must be at least 1, {$limit} given.");
        }
        if ($offset < 0) {
            throw new InvalidArgumentException("The page offset cannot be negative, {$offset} given.");
        }

        return $this->readConcurrently(function () use ($specification, $limit, $offset, $orderBy): array {
            $where = $this->compileOrFallback($specification);
            if ($where === null) {
                // Evaluated in PHP: the page is cut after the filter
                $page = [];
                $skipped = 0;
                foreach ($this->stream(null, $specification, null, null, $orderBy) as $entity) {
                    if ($skipped++ < $offset) {
                        continue;
                    }
                    $page[] = $entity;
                    if (count($page) === $limit) {
                        break;
                    }
                }
                return $page;
            }

            if (!$this->dialect instanceof ISqlPagination) {
                throw new UnsupportedSqlOperationException('LIMIT/OFFSET', $this->family);
            }

            return iterator_to_array($this->stream($where, null, $limit, $offset, $orderBy), false);
        });
    }

    /**
     * The entity with the given identifier, or null.
     *
     * @param mixed $id Identifier value
     * @return T|null
     */
    public function findById(mixed $id): ?IEntity
    {
        if ($id === null) {
            return null;
        }

        return $this->readConcurrently(function () use ($id): ?IEntity {
            $name = ':id';
            $where = new SqlWhereClause(
                $this->dialect->escapeIdentifier($this->idColumn->column) . ' = ' . $name,
                [$name => $this->converter->toDatabase($this->idColumn, $id)]
            );
            foreach ($this->stream($where, null, null, null, []) as $entity) {
                return $entity;
            }

            return null;
        });
    }

    /**
     * {@inheritdoc}
     *
     * By identity: true when a row has the entity's identifier (an entity of another class, or
     * without an identifier yet, is never contained).
     */
    public function contains(IEntity $entity): bool
    {
        return $this->readConcurrently(function () use ($entity): bool {
            $id = $this->identifierOf($entity);

            return $id !== null && $this->rowExists($id);
        });
    }

    ///////////////////////////////////////////////////////////////////////////
    // Writes
    ///////////////////////////////////////////////////////////////////////////

    /** {@inheritdoc} */
    public function put(IEntity $entity): void
    {
        $this->assertMappedEntity($entity);
        $this->writeExclusively(function () use ($entity): void {
            $this->transactions->transactional(function () use ($entity): void {
                $this->save($entity);
            });
        });
    }

    /**
     * {@inheritdoc}
     *
     * All entities are written in one transaction: when one write fails, none is kept.
     */
    public function putAll(array $collectionOfEntities): void
    {
        foreach ($collectionOfEntities as $entity) {
            if (!$entity instanceof IEntity) {
                throw new InvalidArgumentException('All items must implement IEntity.');
            }
            $this->assertMappedEntity($entity);
        }

        $this->writeExclusively(function () use ($collectionOfEntities): void {
            $this->transactions->transactional(function () use ($collectionOfEntities): void {
                foreach ($collectionOfEntities as $entity) {
                    $this->save($entity);
                }
            });
        });
    }

    /**
     * {@inheritdoc}
     *
     * Same as put(): updates the row of the entity, or inserts it when the row does not exist (the
     * upsert of the contract, as in memory). A versioned entity that carries a version whose row is
     * gone throws OptimisticLockException instead of being re-inserted.
     */
    public function update(IEntity $entity): void
    {
        $this->put($entity);
    }

    /** {@inheritdoc} */
    public function remove(IEntity $entity): bool
    {
        return $this->writeExclusively(function () use ($entity): bool {
            $id = $this->identifierOf($entity);
            if ($id === null) {
                return false;
            }

            return $this->transactions->transactional(function () use ($entity, $id): bool {
                $sql = 'DELETE FROM ' . $this->tableSql . ' WHERE ' . $this->quote($this->idColumn->column) . ' = :id';
                $params = [':id' => $id];

                $version = $this->mapping->getVersion();
                $expected = $version !== null ? $this->mapping->readValue($entity, $version->property) : null;
                if ($version !== null && $expected !== null) {
                    $sql .= ' AND ' . $this->quote($version->column) . ' = :version';
                    $params[':version'] = (int) $expected;
                }

                $deleted = $this->run($sql, $params)->rowCount();
                if ($deleted > 0) {
                    return true;
                }
                if ($version !== null && $expected !== null) {
                    $actual = $this->currentVersion($id);
                    if ($actual !== false) {
                        throw new OptimisticLockException($this->mapping->getEntityClass(), $id, (int) $expected, $actual);
                    }
                }

                return false;
            });
        });
    }

    /** {@inheritdoc} */
    public function removeAllEntitiesSpecifiedBy(ISpecification $specification): int
    {
        $this->validateSpecification($specification);

        return $this->writeExclusively(function () use ($specification): int {
            $where = $this->compileOrFallback($specification);

            return $this->transactions->transactional(function () use ($where, $specification): int {
                if ($where !== null) {
                    return $this->run('DELETE FROM ' . $this->tableSql . $this->whereSql($where), $where->getParameters())->rowCount();
                }

                // Evaluated in PHP: collect the identifiers first, then delete them in chunks
                $ids = [];
                foreach ($this->stream(null, $specification) as $entity) {
                    $ids[] = $this->identifierOf($entity);
                }
                $removed = 0;
                foreach (array_chunk($ids, self::DELETE_CHUNK) as $chunk) {
                    $params = [];
                    foreach ($chunk as $i => $id) {
                        $params[':id' . $i] = $id;
                    }
                    $removed += $this->run(
                        'DELETE FROM ' . $this->tableSql . ' WHERE ' . $this->quote($this->idColumn->column)
                        . ' IN (' . implode(', ', array_keys($params)) . ')',
                        $params
                    )->rowCount();
                }

                return $removed;
            });
        });
    }

    /**
     * {@inheritdoc}
     *
     * @throws PartitioningNotSupportedException Always: a table is partitioned by the database (D9)
     */
    public function makePartition(?ISpecification $specification = null): IPartitionRepository
    {
        throw new PartitioningNotSupportedException(static::class, (string) $this->mapping->getTable());
    }

    ///////////////////////////////////////////////////////////////////////////
    // Hydration
    ///////////////////////////////////////////////////////////////////////////

    /**
     * Builds an entity from a fetched row (columns in mapping order) without calling its constructor
     * (D3). An AbstractEntity whose creation time is not mapped gets the hydration time, as an entity
     * built in memory gets its construction time.
     *
     * @param list<mixed> $row Column values in the order of the mapping
     * @return T
     */
    protected function hydrate(array $row): IEntity
    {
        $entity = $this->mapping->instantiate();
        foreach ($this->columnList as $i => $column) {
            $this->mapping->writeValue($entity, $column->property, $this->converter->fromDatabase($column, $row[$i] ?? null));
        }

        if ($entity instanceof AbstractEntity) {
            $property = self::$timeOfCreation ??= new ReflectionProperty(AbstractEntity::class, 'timeOfCreation');
            if (!$property->isInitialized($entity)) {
                $property->setValue($entity, new DateTimeImmutable());
            }
        }

        return $entity;
    }

    ///////////////////////////////////////////////////////////////////////////
    // Internals
    ///////////////////////////////////////////////////////////////////////////

    private function compiler(): PdoSpecificationCompiler
    {
        return new PdoSpecificationCompiler($this->mapping, $this->dialect, $this->converter);
    }

    /**
     * The compiled clause, or null when the specification cannot be translated and the in-memory
     * fallback is on.
     */
    private function compileOrFallback(ISpecification $specification): ?SqlWhereClause
    {
        try {
            return $this->compiler()->translate($specification);
        } catch (NonTranslatableSpecificationException | UnsupportedSqlOperationException $e) {
            if ($this->inMemoryFallback) {
                return null;
            }
            throw $e;
        }
    }

    /**
     * Streams the entities of a SELECT, filtering in PHP when a specification is given.
     *
     * @param array<string, string> $orderBy
     * @return Generator<int, T>
     */
    private function stream(
        ?SqlWhereClause $where,
        ?ISpecification $memoryFilter,
        ?int $limit = null,
        ?int $offset = null,
        array $orderBy = []
    ): Generator {
        $sql = $this->selectSql . ($where !== null ? $this->whereSql($where) : '') . $this->orderSql($orderBy);
        if (($limit !== null || $offset !== null) && $this->dialect instanceof ISqlPagination) {
            $sql = $this->dialect->paginate($sql, $limit, $offset);
        }

        $statement = $this->run($sql, $where?->getParameters() ?? []);
        try {
            while (($row = $statement->fetch(PDO::FETCH_NUM)) !== false) {
                $entity = $this->hydrate($row);
                if ($memoryFilter === null || $memoryFilter->isSatisfiedBy($entity)) {
                    yield $entity;
                }
            }
        } finally {
            $statement->closeCursor();
        }
    }

    private function whereSql(SqlWhereClause $where): string
    {
        return $where->isEmpty() ? '' : ' WHERE ' . $where->toSql();
    }

    /**
     * @param array<string, string> $orderBy
     */
    private function orderSql(array $orderBy): string
    {
        $terms = [];
        $seenId = false;
        foreach ($orderBy as $property => $direction) {
            $reason = null;
            $column = is_string($property) ? $this->mapping->findQueryColumn($property, $reason) : null;
            if ($column === null) {
                throw new InvalidArgumentException(sprintf('Cannot order by "%s": %s.', (string) $property, (string) ($reason ?? 'not a property name')));
            }
            $dir = strtoupper(trim((string) $direction));
            if ($dir !== 'ASC' && $dir !== 'DESC') {
                throw new InvalidArgumentException(sprintf('Order direction of "%s" must be ASC or DESC, "%s" given.', $property, (string) $direction));
            }
            $terms[] = $this->quote($column->column) . ' ' . $dir;
            $seenId = $seenId || $column->isId;
        }
        if (!$seenId) {
            $terms[] = $this->quote($this->idColumn->column) . ' ASC';
        }

        return ' ORDER BY ' . implode(', ', $terms);
    }

    /**
     * Inserts or updates one entity (inside the caller's transaction).
     */
    private function save(IEntity $entity): void
    {
        $id = $this->identifierOf($entity);
        if ($id === null) {
            $this->insert($entity, true);
            return;
        }

        $version = $this->mapping->getVersion();
        $current = $this->currentVersion($id);
        if ($current === false) {
            if ($version !== null && $this->mapping->readValue($entity, $version->property) !== null) {
                // A versioned copy whose row is gone: removed by someone else, never resurrected
                throw new OptimisticLockException(
                    $this->mapping->getEntityClass(),
                    $id,
                    (int) $this->mapping->readValue($entity, $version->property),
                    null
                );
            }
            $this->insert($entity, false);
            return;
        }

        $this->updateRow($entity, $id, $current);
    }

    private function insert(IEntity $entity, bool $generateId): void
    {
        $returning = false;
        $id = $this->idColumn;

        if ($generateId) {
            $generated = match ($this->mapping->getIdStrategy()) {
                IdStrategy::Auto => null,
                IdStrategy::Ulid => UlidGenerator::shared()->generate(),
                IdStrategy::Uuid7 => UuidV7Generator::shared()->generate(),
                IdStrategy::Max => $this->nextMaxId(),
                IdStrategy::Assigned => throw new InvalidArgumentException(sprintf(
                    '%s uses assigned identifiers: set "%s" before putting it.',
                    $this->mapping->getEntityClass(),
                    $id->property
                )),
            };
            if ($generated !== null) {
                $this->mapping->writeValue($entity, $id->property, $generated);
            }
        }

        $version = $this->mapping->getVersion();
        $newVersion = null;
        if ($version !== null) {
            $carried = $this->mapping->readValue($entity, $version->property);
            $newVersion = $carried !== null ? (int) $carried : 1;
        }

        $columns = [];
        $params = [];
        foreach ($this->columnList as $i => $column) {
            if ($column->isId && $generateId && $this->mapping->getIdStrategy() === IdStrategy::Auto) {
                continue;
            }
            $value = $column->isVersion ? $newVersion : $this->mapping->readValue($entity, $column->property);
            $name = ':c' . $i;
            $columns[] = $this->quote($column->column);
            $params[$name] = $this->converter->toDatabase($column, $value);
        }

        $sql = 'INSERT INTO ' . $this->tableSql . ' (' . implode(', ', $columns) . ') VALUES (' . implode(', ', array_keys($params)) . ')';
        $autoId = $generateId && $this->mapping->getIdStrategy() === IdStrategy::Auto;
        if ($autoId && $this->family === 'pgsql' && $this->mapping->getSequence() === null) {
            $sql .= ' RETURNING ' . $this->quote($id->column);
            $returning = true;
        }
        if ($columns === []) {
            $sql = 'INSERT INTO ' . $this->tableSql . ' DEFAULT VALUES' . ($returning ? ' RETURNING ' . $this->quote($id->column) : '');
        }

        $statement = $this->run($sql, $params);

        if ($autoId) {
            if ($returning) {
                $raw = $statement->fetchColumn();
                $statement->closeCursor();
            } else {
                try {
                    $raw = $this->pdo->lastInsertId($this->mapping->getSequence());
                } catch (PDOException $e) {
                    throw new PdoRepositoryException('Could not read the generated identifier: ' . $e->getMessage(), null, $e);
                }
            }
            if ($raw === false || $raw === null || $raw === '' || $raw === '0') {
                throw new PdoRepositoryException(sprintf(
                    'The database generated no identifier for %s (is "%s" an identity/auto-increment column%s?).',
                    $this->mapping->getEntityClass(),
                    $id->column,
                    $this->family === 'pgsql' ? ' or is the sequence name right' : ''
                ));
            }
            $this->mapping->writeValue($entity, $id->property, $this->converter->fromDatabase($id, $raw));
        }

        if ($version !== null) {
            $this->mapping->writeValue($entity, $version->property, $newVersion);
        }
    }

    /**
     * @param int|false|null $current Version stored in the row (null when the row holds none)
     */
    private function updateRow(IEntity $entity, mixed $id, int|false|null $current): void
    {
        $version = $this->mapping->getVersion();

        $sets = [];
        $params = [];
        foreach ($this->columnList as $i => $column) {
            if ($column->isId || $column->isVersion) {
                continue;
            }
            $name = ':c' . $i;
            $sets[] = $this->quote($column->column) . ' = ' . $name;
            $params[$name] = $this->converter->toDatabase($column, $this->mapping->readValue($entity, $column->property));
        }

        $where = $this->quote($this->idColumn->column) . ' = :id';
        $params[':id'] = $id;

        $newVersion = null;
        if ($version !== null) {
            $expected = $this->mapping->readValue($entity, $version->property);
            $newVersion = ($expected !== null ? (int) $expected : 0) + 1;
            $sets[] = $this->quote($version->column) . ' = :new_version';
            $params[':new_version'] = $newVersion;
            if ($expected === null) {
                $where .= ' AND ' . $this->quote($version->column) . ' IS NULL';
            } else {
                $where .= ' AND ' . $this->quote($version->column) . ' = :expected_version';
                $params[':expected_version'] = (int) $expected;
            }
        }

        if ($sets === []) {
            return;
        }

        $updated = $this->run('UPDATE ' . $this->tableSql . ' SET ' . implode(', ', $sets) . ' WHERE ' . $where, $params)->rowCount();

        if ($version !== null) {
            if ($updated === 0) {
                $expected = $this->mapping->readValue($entity, $version->property);
                $actual = $this->currentVersion($id);
                throw new OptimisticLockException(
                    $this->mapping->getEntityClass(),
                    $id,
                    $expected !== null ? (int) $expected : null,
                    $actual === false ? null : $actual
                );
            }
            $this->mapping->writeValue($entity, $version->property, $newVersion);
        }
    }

    /**
     * Version stored in the row of the identifier: false when the row does not exist, null when the
     * entity is not versioned or the row holds no version.
     */
    private function currentVersion(mixed $id): int|false|null
    {
        $version = $this->mapping->getVersion();
        $select = $version !== null ? $this->quote($version->column) : '1';
        $statement = $this->run(
            'SELECT ' . $select . ' FROM ' . $this->tableSql . ' WHERE ' . $this->quote($this->idColumn->column) . ' = :id',
            [':id' => $id]
        );
        $row = $statement->fetch(PDO::FETCH_NUM);
        $statement->closeCursor();

        if ($row === false) {
            return false;
        }

        return ($version !== null && $row[0] !== null) ? (int) $row[0] : null;
    }

    private function rowExists(mixed $id): bool
    {
        $statement = $this->run(
            'SELECT 1 FROM ' . $this->tableSql . ' WHERE ' . $this->quote($this->idColumn->column) . ' = :id',
            [':id' => $id]
        );
        $exists = $statement->fetch(PDO::FETCH_NUM) !== false;
        $statement->closeCursor();

        return $exists;
    }

    private function nextMaxId(): int
    {
        $statement = $this->run('SELECT COALESCE(MAX(' . $this->quote($this->idColumn->column) . '), 0) + 1 FROM ' . $this->tableSql);
        $next = $statement->fetchColumn();
        $statement->closeCursor();

        return (int) $next;
    }

    /**
     * Bindable identifier of an entity of the mapped class, or null when it has none yet (or is of
     * another class).
     */
    private function identifierOf(IEntity $entity): mixed
    {
        $class = $this->mapping->getEntityClass();
        if (!$entity instanceof $class) {
            return null;
        }
        $value = $this->mapping->readValue($entity, $this->idColumn->property);

        return $value === null ? null : $this->converter->toDatabase($this->idColumn, $value);
    }

    private function assertMappedEntity(IEntity $entity): void
    {
        $class = $this->mapping->getEntityClass();
        if (!$entity instanceof $class) {
            throw new InvalidArgumentException(sprintf(
                'This repository stores %s; %s cannot be written to table "%s".',
                $class,
                get_class($entity),
                (string) $this->mapping->getTable()
            ));
        }
    }

    private function quote(string $identifier): string
    {
        return $this->dialect->escapeIdentifier($identifier);
    }

    /**
     * Prepares and runs a statement with bound parameters.
     *
     * @param array<string, mixed> $params Named parameters, already converted for their columns
     * @throws PdoRepositoryException When the driver reports an error
     */
    private function run(string $sql, array $params = []): PDOStatement
    {
        try {
            $statement = $this->pdo->prepare($sql);
            if (!$statement instanceof PDOStatement) {
                throw $this->driverError($this->pdo->errorInfo(), $sql);
            }
            foreach ($params as $name => $value) {
                $value = $this->converter->scalarOrString($value);
                $statement->bindValue($name, $value, $this->converter->bindType($value));
            }
            if (!$statement->execute()) {
                throw $this->driverError($statement->errorInfo(), $sql);
            }
        } catch (PDOException $e) {
            $info = $e->errorInfo;
            throw new PdoRepositoryException(
                sprintf('Statement on table "%s" failed: %s', (string) $this->mapping->getTable(), $e->getMessage()),
                is_array($info) && isset($info[0]) ? (string) $info[0] : (is_string($e->getCode()) ? $e->getCode() : null),
                $e
            );
        }

        return $statement;
    }

    /**
     * @param array<int, mixed> $errorInfo PDO errorInfo() triple
     */
    private function driverError(array $errorInfo, string $sql): PdoRepositoryException
    {
        return new PdoRepositoryException(
            sprintf(
                'Statement on table "%s" failed: [%s] %s',
                (string) $this->mapping->getTable(),
                (string) ($errorInfo[0] ?? ''),
                (string) ($errorInfo[2] ?? 'unknown driver error')
            ),
            isset($errorInfo[0]) ? (string) $errorInfo[0] : null
        );
    }
}
