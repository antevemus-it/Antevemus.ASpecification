/**
 * PdoFeatureFlagStore - Feature Flags in Relational Tables over PDO
 *
 * The relational IFeatureFlagStore (forward 034, D3). Reads and writes the tables of the reference DDL
 * `resources/sql/feature_flags.ansi.sql` by default: `feature_flag` (one row per flag: the switch, the
 * validity window, who turned it on and off last), `feature_flag_change` (the append-only history) and
 * `feature_flag_subject` (the subject lists). Same contract as InMemoryFeatureFlagStore (RN-02).
 *
 * Existing tables are read where they are, in the conventions of PdoRuleCatalog:
 * - `$tables`: name by role (`flag`, `change`, `subject`); `subject => null` = the database keeps no
 *   subject lists (adding a subject is refused; evaluation sees empty lists)
 * - `$columns`: by role, canonical column => real column; a canonical column mapped to null is a
 *   feature that table does not have (no validity window, no version, no stamp of who turned it off).
 *   The canonical columns are the names of the reference DDL, plus five that it does not declare and
 *   that are absent by default: `created_at`, `created_by`, `updated_at`, `updated_by` (stamped when
 *   mapped) and `deleted_at` (when mapped, only rows where it is NULL exist). Every real column is
 *   selected under its canonical alias, so hydration never depends on the real names
 * - `$changeScope`: fixed values (real column => value) that identify the flag rows of a history table
 *   shared with other audit trails (e.g. `['entity_type' => 'feature_flag', 'field' => 'enabled']`):
 *   written on every row appended and required on every row read
 * - `$booleans`: storage of the boolean columns by role (`flag`: `enabled`; `change`: `old_enabled`
 *   and `new_enabled`), as a BooleanStorage case (Native, Integer, or Char for 'Y'/'N') or as a pair of
 *   texts `[true, false]` (e.g. `['true', 'false']`); the reference DDL stores 'Y'/'N'. A Char column is
 *   read strictly: any other stored text is a FeatureFlagStoreException, never a silent false
 * - `$timestampFormat` and `$timezone`: how instants are written and read (default: UTC,
 *   'Y-m-d H:i:s.u', the fixed-width text of the package DDLs). Instants are read leniently (any text
 *   DateTimeImmutable accepts, in that zone); a validity bound stored as a date only covers the whole day
 * - `$databaseGeneratedChangeId`: the history key is generated by the database (an identity or serial
 *   column): it is then left out of the INSERT and still used to order the history. Otherwise, when
 *   `change_id` is mapped, the store writes a ULID
 *
 * SQL: portable and parameterized; every identifier validated against `[A-Za-z_][A-Za-z0-9_]*`, every
 * value bound, named placeholders used once each (safe under native prepares). loadAll() is one query
 * (flags LEFT JOIN subjects). The switch is changed by compare-and-set (`UPDATE ... WHERE code = :code
 * AND enabled = :expected`, one row or nothing). A row is created by "check, then INSERT": when another
 * writer created it in between, the key rejects the INSERT and the call reports "already there"; on
 * PostgreSQL inside a transaction the INSERT runs under a savepoint, so the rejected INSERT does not
 * abort the caller's transaction (the approach of PdoTriggerStateStore, instead of a dialect-specific
 * `ON CONFLICT`). The error mode of the connection is left untouched: failed statements are detected
 * both ways and reported as FeatureFlagStoreException with the driver message and the SQLSTATE.
 *
 * withQueryLogger() sends every statement to an IQueryLogger (the hook of PdoRepository, 1.13.0).
 *
 * 2.3.0 (forward 040): the validity window and the rollout percentage are written by compare-and-set of
 * the optimistic version (`UPDATE ... SET ..., version = version + 1 WHERE code = :code AND version =
 * :expected_version`, one row or nothing); the switch increments the version too. The window needs
 * `valid_from`, `valid_until` and `version` (supportsValidity()); the rollout needs `rollout_percent`
 * and `version` (supportsRollout()). The columns that the reference DDL gained in 2.3.0
 * (COLUMNS_SINCE_2_3: `feature_flag.rollout_percent`, `feature_flag_change.change_kind` and
 * `feature_flag_change.detail`) are absent by default, so that a table created by the DDL of 2.1.0
 * keeps being read and written as before (a table without them answers like 2.2.0: no rollout, every
 * history row written without kind nor detail). A table that has them says so with
 * `columns: PdoFeatureFlagStore::COLUMNS_SINCE_2_3` (merged with any other mapping). Without
 * `change_kind`, a history row reads as a Subject change when it has a subject key and as a Toggle
 * otherwise; a stored `change_kind` of `toggle` with a subject key (a 2.1.0 row after the additive
 * migration) reads as Subject.
 *
 * @version    2.3.0
 * @package    Antevemus\ASpecification
 * @subpackage FeatureFlags
 * @author     Heliton Junior (CTO) - <contato@antevemus.com.br>
 * @copyright  Copyright (c) 2025-2026 Antevemus Soluções Inovadoras em TI Ltda.
 * @license    MIT
 */
final class PdoFeatureFlagStore implements IFeatureFlagStore
{
    /** Default table names by role, mirroring the reference DDL. */
    public const DEFAULT_TABLES = [
        'flag' => 'feature_flag',
        'change' => 'feature_flag_change',
        'subject' => 'feature_flag_subject',
    ];

    /** Canonical columns of the flag table declared by the reference DDL (mapped to themselves by default). */
    public const FLAG_COLUMNS = [
        'code', 'name', 'description', 'category', 'enabled', 'audience', 'notes', 'valid_from', 'valid_until',
        'enabled_at', 'enabled_by', 'disabled_at', 'disabled_by', 'version',
    ];

    /** Canonical columns of the flag table that the reference DDL does not declare (absent by default). */
    public const FLAG_OPTIONAL_COLUMNS = ['created_at', 'created_by', 'updated_at', 'updated_by', 'deleted_at'];

    /** Canonical columns of the flag table added to the reference DDL in 2.3.0 (absent by default). */
    public const FLAG_COLUMNS_SINCE_2_3 = ['rollout_percent'];

    /** Canonical columns of the history table added to the reference DDL in 2.3.0 (absent by default). */
    public const CHANGE_COLUMNS_SINCE_2_3 = ['change_kind', 'detail'];

    /**
     * Column map of a table created (or migrated) by the reference DDL of 2.3.0: the rollout percentage
     * and the kind and detail of the history rows. Pass it as `$columns` (merged with any other mapping).
     */
    public const COLUMNS_SINCE_2_3 = [
        'flag' => ['rollout_percent' => 'rollout_percent'],
        'change' => ['change_kind' => 'change_kind', 'detail' => 'detail'],
    ];

    /** Canonical columns of the history table. */
    public const CHANGE_COLUMNS = [
        'change_id', 'flag_code', 'subject_key', 'old_enabled', 'new_enabled', 'reason', 'origin', 'changed_at', 'changed_by',
    ];

    /** Canonical columns of the subject table. */
    public const SUBJECT_COLUMNS = ['flag_code', 'subject_key'];

    /** Canonical columns that cannot be mapped to null, by role. */
    public const REQUIRED_COLUMNS = [
        'flag' => ['code', 'enabled'],
        'change' => ['flag_code', 'new_enabled', 'reason', 'origin', 'changed_at'],
        'subject' => ['flag_code', 'subject_key'],
    ];

    /** Default format of the instants written (fixed-width text, as in the other package DDLs). */
    public const DEFAULT_TIMESTAMP_FORMAT = 'Y-m-d H:i:s.u';

    private const IDENTIFIER = '/^[A-Za-z_][A-Za-z0-9_]*$/';

    private const SAVEPOINT = 'aspec_feature_flag';

    /** Flag columns read by loadAll() and find(), besides code and enabled. */
    private const FLAG_READ = [
        'name', 'description', 'category', 'audience', 'notes', 'valid_from', 'valid_until',
        'enabled_at', 'enabled_by', 'disabled_at', 'disabled_by', 'version', 'rollout_percent',
    ];

    /** @var array{flag: string, change: string, subject: string|null} Schema-qualified table names */
    private readonly array $tables;

    /** @var array{flag: array<string, string|null>, change: array<string, string|null>, subject: array<string, string|null>} */
    private readonly array $columns;

    /** @var array<string, string|int> */
    private readonly array $changeScope;

    /** @var array{flag: array{BooleanStorage, string, string}, change: array{BooleanStorage, string, string}} */
    private readonly array $booleans;

    private readonly DateTimeZone $zone;

    private readonly ITransactionManager $transactions;

    private readonly ?ISqlPagination $pagination;

    private readonly string $driver;

    private ?IQueryLogger $logger = null;

    private bool $logParameters = false;

    /**
     * @param PDO $pdo Connection to the database holding the tables (its error mode is left untouched)
     * @param string $schema Optional schema (or database) qualifying every table; '' = unqualified
     * @param array<string, string|null> $tables Table names by role (`flag`, `change`, `subject`); missing
     *                                           roles keep the default; `subject => null` = no subject lists
     * @param array<string, array<string, string|null>> $columns By role, canonical column => real column
     *                                                           (null = absent from that table)
     * @param array<string, string|int> $changeScope Fixed values of the history table (real column => value)
     * @param array<string, BooleanStorage|array{0: string, 1: string}> $booleans Boolean storage by role (`flag`, `change`)
     * @param string $timestampFormat date() format of the instants written
     * @param string $timezone Time zone of the instants written and read
     * @param bool $databaseGeneratedChangeId True when the database generates the history key (`change_id`)
     * @param ITransactionManager|null $transactions Unit of work (null = a PdoTransactionManager on $pdo)
     * @throws InvalidArgumentException When a name is not a plain SQL identifier, a role or a canonical column
     *                                  is unknown, a required column is mapped to null, or an option is invalid
     */
    public function __construct(
        private readonly PDO $pdo,
        string $schema = '',
        array $tables = self::DEFAULT_TABLES,
        array $columns = [],
        array $changeScope = [],
        array $booleans = [],
        private readonly string $timestampFormat = self::DEFAULT_TIMESTAMP_FORMAT,
        string $timezone = 'UTC',
        private readonly bool $databaseGeneratedChangeId = false,
        ?ITransactionManager $transactions = null
    ) {
        if ($schema !== '' && preg_match(self::IDENTIFIER, $schema) !== 1) {
            throw new InvalidArgumentException(sprintf('Feature flag schema "%s" is not a plain SQL identifier.', $schema));
        }

        $resolved = [];
        foreach ($tables as $role => $name) {
            if (!array_key_exists($role, self::DEFAULT_TABLES)) {
                throw new InvalidArgumentException(sprintf(
                    'Unknown feature flag table role "%s". Expected: %s.',
                    (string) $role,
                    implode(', ', array_keys(self::DEFAULT_TABLES))
                ));
            }
        }
        foreach (self::DEFAULT_TABLES as $role => $default) {
            $name = array_key_exists($role, $tables) ? $tables[$role] : $default;
            if ($name === null && $role === 'subject') {
                $resolved[$role] = null;
                continue;
            }
            if (!is_string($name) || preg_match(self::IDENTIFIER, $name) !== 1) {
                throw new InvalidArgumentException(sprintf(
                    'Feature flag table "%s" (role %s) is not a plain SQL identifier.',
                    is_string($name) ? $name : get_debug_type($name),
                    $role
                ));
            }
            $resolved[$role] = $schema !== '' ? $schema . '.' . $name : $name;
        }
        /** @var array{flag: string, change: string, subject: string|null} $resolved */
        $this->tables = $resolved;

        $this->columns = $this->resolveColumns($columns);
        if ($this->tables['subject'] !== null && $this->columns['change']['subject_key'] === null) {
            throw new InvalidArgumentException('A subject table needs the subject_key column of the history table (subject changes are recorded there).');
        }
        if ($databaseGeneratedChangeId && $this->columns['change']['change_id'] === null) {
            throw new InvalidArgumentException('databaseGeneratedChangeId needs the change_id column of the history table.');
        }

        $scope = [];
        foreach ($changeScope as $column => $value) {
            if (!is_string($column) || preg_match(self::IDENTIFIER, $column) !== 1) {
                throw new InvalidArgumentException(sprintf('History scope column "%s" is not a plain SQL identifier.', (string) $column));
            }
            if (!is_string($value) && !is_int($value)) {
                throw new InvalidArgumentException(sprintf('History scope column "%s" needs a string or integer value.', $column));
            }
            if (in_array($column, array_filter($this->columns['change']), true)) {
                throw new InvalidArgumentException(sprintf('History scope column "%s" is already mapped to a canonical column.', $column));
            }
            $scope[$column] = $value;
        }
        $this->changeScope = $scope;

        $this->booleans = [
            'flag' => self::resolveBoolean('flag', $booleans['flag'] ?? BooleanStorage::Char),
            'change' => self::resolveBoolean('change', $booleans['change'] ?? BooleanStorage::Char),
        ];
        foreach (array_keys($booleans) as $role) {
            if ($role !== 'flag' && $role !== 'change') {
                throw new InvalidArgumentException(sprintf('Unknown boolean role "%s". Expected: flag, change.', (string) $role));
            }
        }

        if (trim($timestampFormat) === '') {
            throw new InvalidArgumentException('The timestamp format cannot be empty.');
        }
        try {
            $this->zone = new DateTimeZone($timezone);
        } catch (Exception $e) {
            throw new InvalidArgumentException(sprintf('Unknown time zone "%s".', $timezone), 0, $e);
        }

        $this->transactions = $transactions ?? new PdoTransactionManager($pdo);
        $this->driver = (string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
        $dialect = SqlDialectFactory::create(SqlDialect::fromDriver($this->driver));
        $this->pagination = $dialect instanceof ISqlPagination ? $dialect : null;
    }

    /**
     * Every canonical column, by role.
     *
     * @return array{flag: list<string>, change: list<string>, subject: list<string>}
     */
    public static function canonicalColumns(): array
    {
        return [
            'flag' => [...self::FLAG_COLUMNS, ...self::FLAG_OPTIONAL_COLUMNS, ...self::FLAG_COLUMNS_SINCE_2_3],
            'change' => [...self::CHANGE_COLUMNS, ...self::CHANGE_COLUMNS_SINCE_2_3],
            'subject' => self::SUBJECT_COLUMNS,
        ];
    }

    /**
     * Sends every statement to a logger, or stops logging (null). The parameter values are logged only
     * when $logParameters is true: they can be personal data (an actor, a subject key, a reason).
     *
     * @return $this
     */
    public function withQueryLogger(?IQueryLogger $logger, bool $logParameters = false): self
    {
        $this->logger = $logger;
        $this->logParameters = $logger !== null && $logParameters;

        return $this;
    }

    /** The query logger, or null. */
    public function getQueryLogger(): ?IQueryLogger
    {
        return $this->logger;
    }

    /** The connection. */
    public function getPdo(): PDO
    {
        return $this->pdo;
    }

    /**
     * Schema-qualified table names in use, by role (`subject` null = no subject lists).
     *
     * @return array{flag: string, change: string, subject: string|null}
     */
    public function getTables(): array
    {
        return $this->tables;
    }

    /**
     * Real column of every canonical column, by role (null = absent).
     *
     * @return array{flag: array<string, string|null>, change: array<string, string|null>, subject: array<string, string|null>}
     */
    public function getColumns(): array
    {
        return $this->columns;
    }

    /** {@inheritdoc} */
    public function loadAll(): array
    {
        $states = [];
        foreach ($this->groupRows($this->fetchAll($this->selectFlags(false), [])) as $code => $rows) {
            $states[$code] = $this->hydrateState($rows);
        }

        return $states;
    }

    /** {@inheritdoc} */
    public function find(string $code): ?FeatureFlagState
    {
        $grouped = $this->groupRows($this->fetchAll($this->selectFlags(true), [':code' => $code]));

        return isset($grouped[$code]) ? $this->hydrateState($grouped[$code]) : null;
    }

    /** {@inheritdoc} */
    public function insertIfAbsent(FeatureFlagDefinition $definition, DateTimeImmutable $at, string|int|null $actor): bool
    {
        if ($this->rowExists($definition->code, false)) {
            return false;
        }

        $values = [
            'code' => $definition->code,
            'enabled' => $this->booleanToDatabase('flag', false),
            'name' => $definition->name,
        ];
        foreach (['description', 'category', 'audience'] as $text) {
            if ($definition->{$text} !== '') {
                $values[$text] = $definition->{$text};
            }
        }
        $values['version'] = 1;
        $values['created_at'] = $this->toText($at);
        $values['created_by'] = $actor;

        $columns = [];
        $params = [];
        foreach ($values as $canonical => $value) {
            $real = $this->columns['flag'][$canonical];
            if ($real === null) {
                continue;
            }
            $columns[] = $real;
            $params[':v_' . $canonical] = $value;
        }
        $sql = sprintf(
            'INSERT INTO %s (%s) VALUES (%s)',
            $this->tables['flag'],
            implode(', ', $columns),
            implode(', ', array_keys($params))
        );

        return $this->insertUnlessRaced($sql, $params, fn(): bool => $this->rowExists($definition->code, true));
    }

    /** {@inheritdoc} */
    public function compareAndSetEnabled(string $code, bool $expected, bool $enabled, DateTimeImmutable $at, string|int|null $actor): bool
    {
        $flag = $this->columns['flag'];
        $now = $this->toText($at);
        $set = [$flag['enabled'] . ' = :new_enabled'];
        $params = [':new_enabled' => $this->booleanToDatabase('flag', $enabled)];
        $stamps = $enabled ? ['enabled_at' => $now, 'enabled_by' => $actor] : ['disabled_at' => $now, 'disabled_by' => $actor];
        $stamps += ['updated_at' => $now, 'updated_by' => $actor];
        foreach ($stamps as $canonical => $value) {
            if ($flag[$canonical] !== null) {
                $set[] = $flag[$canonical] . ' = :s_' . $canonical;
                $params[':s_' . $canonical] = $value;
            }
        }
        if ($flag['version'] !== null) {
            $set[] = sprintf('%1$s = %1$s + 1', $flag['version']);
        }

        $where = [$flag['code'] . ' = :code', $this->booleanPredicate('flag', $flag['enabled'], $expected, 'expected', $params)];
        $params[':code'] = $code;
        if ($flag['deleted_at'] !== null) {
            $where[] = $flag['deleted_at'] . ' IS NULL';
        }

        return $this->execute(sprintf(
            'UPDATE %s SET %s WHERE %s',
            $this->tables['flag'],
            implode(', ', $set),
            implode(' AND ', $where)
        ), $params)->rowCount() === 1;
    }

    /** {@inheritdoc} */
    public function supportsValidity(): bool
    {
        return $this->absentFlagColumns(['valid_from', 'valid_until', 'version']) === [];
    }

    /** {@inheritdoc} */
    public function compareAndSetValidity(string $code, int $expectedVersion, ?DateTimeImmutable $from, ?DateTimeImmutable $until, DateTimeImmutable $at, string|int|null $actor): bool
    {
        $this->assertFlagColumns('validity window', ['valid_from', 'valid_until', 'version']);

        return $this->compareAndSetVersion($code, $expectedVersion, [
            'valid_from' => $from === null ? null : $this->toText($from),
            'valid_until' => $until === null ? null : $this->toText($until),
        ], $at, $actor);
    }

    /** {@inheritdoc} */
    public function supportsRollout(): bool
    {
        return $this->absentFlagColumns(['rollout_percent', 'version']) === [];
    }

    /** {@inheritdoc} */
    public function compareAndSetRollout(string $code, int $expectedVersion, ?int $percent, DateTimeImmutable $at, string|int|null $actor): bool
    {
        $this->assertFlagColumns('rollout percentage', ['rollout_percent', 'version']);
        if ($percent !== null && ($percent < 0 || $percent > 100)) {
            throw new InvalidArgumentException(sprintf('The rollout percentage must be between 0 and 100, %d given.', $percent));
        }

        return $this->compareAndSetVersion($code, $expectedVersion, ['rollout_percent' => $percent], $at, $actor);
    }

    /** {@inheritdoc} */
    public function supportsSubjects(): bool
    {
        return $this->tables['subject'] !== null;
    }

    /** {@inheritdoc} */
    public function addSubject(string $code, string $subjectKey): bool
    {
        $table = $this->subjectTable();
        $subject = $this->columns['subject'];
        if ($this->subjectExists($code, $subjectKey, false)) {
            return false;
        }

        return $this->insertUnlessRaced(
            sprintf('INSERT INTO %s (%s, %s) VALUES (:code, :subject_key)', $table, $subject['flag_code'], $subject['subject_key']),
            [':code' => $code, ':subject_key' => $subjectKey],
            fn(): bool => $this->subjectExists($code, $subjectKey, true)
        );
    }

    /** {@inheritdoc} */
    public function removeSubject(string $code, string $subjectKey): bool
    {
        $table = $this->subjectTable();
        $subject = $this->columns['subject'];

        return $this->execute(
            sprintf('DELETE FROM %s WHERE %s = :code AND %s = :subject_key', $table, $subject['flag_code'], $subject['subject_key']),
            [':code' => $code, ':subject_key' => $subjectKey]
        )->rowCount() === 1;
    }

    /** {@inheritdoc} */
    public function appendChange(FeatureFlagChange $change): void
    {
        $map = $this->columns['change'];
        if ($change->subjectKey !== null && $map['subject_key'] === null) {
            throw new FeatureFlagStoreException('The history table has no subject_key column: subject changes cannot be recorded.');
        }

        $values = [
            'flag_code' => $change->code,
            'subject_key' => $change->subjectKey,
            'old_enabled' => $change->oldEnabled === null ? null : $this->booleanToDatabase('change', $change->oldEnabled),
            'new_enabled' => $this->booleanToDatabase('change', $change->newEnabled),
            'reason' => $change->reason,
            'origin' => $change->origin,
            'changed_at' => $this->toText($change->changedAt),
            'changed_by' => $change->changedBy,
            'change_kind' => $change->kind->value,
            'detail' => $change->detail,
        ];
        if (!$this->databaseGeneratedChangeId) {
            $values = ['change_id' => UlidGenerator::shared()->generate()] + $values;
        }

        $columns = [];
        $params = [];
        foreach ($values as $canonical => $value) {
            $real = $map[$canonical];
            if ($real === null) {
                continue;
            }
            $columns[] = $real;
            $params[':v_' . $canonical] = $value;
        }
        $i = 0;
        foreach ($this->changeScope as $column => $value) {
            $columns[] = $column;
            $params[':scope_' . $i++] = $value;
        }

        $this->execute(sprintf(
            'INSERT INTO %s (%s) VALUES (%s)',
            $this->tables['change'],
            implode(', ', $columns),
            implode(', ', array_keys($params))
        ), $params);
    }

    /** {@inheritdoc} */
    public function history(?string $code = null, int $limit = 50): array
    {
        if ($limit < 1) {
            throw new InvalidArgumentException(sprintf('The history limit must be at least 1, %d given.', $limit));
        }
        $change = $this->columns['change'];
        $select = [];
        foreach ([...self::CHANGE_COLUMNS, ...self::CHANGE_COLUMNS_SINCE_2_3] as $canonical) {
            if ($change[$canonical] !== null) {
                $select[] = $change[$canonical] . ' AS ' . $canonical;
            }
        }
        $where = [];
        $params = [];
        if ($code !== null) {
            $where[] = $change['flag_code'] . ' = :code';
            $params[':code'] = $code;
        }
        $i = 0;
        foreach ($this->changeScope as $column => $value) {
            $where[] = sprintf('%s = :scope_%d', $column, $i);
            $params[':scope_' . $i++] = $value;
        }
        $order = [$change['changed_at'] . ' DESC'];
        if ($change['change_id'] !== null) {
            $order[] = $change['change_id'] . ' DESC';
        }
        $sql = sprintf(
            'SELECT %s FROM %s%s ORDER BY %s',
            implode(', ', $select),
            $this->tables['change'],
            $where === [] ? '' : ' WHERE ' . implode(' AND ', $where),
            implode(', ', $order)
        );
        if ($this->pagination !== null) {
            $sql = $this->pagination->paginate($sql, $limit);
        }

        $rows = [];
        foreach (array_slice($this->fetchAll($sql, $params), 0, $limit) as $row) {
            $subjectKey = self::nullableText($row['subject_key'] ?? null);
            $rows[] = new FeatureFlagChange(
                (string) $row['flag_code'],
                ($row['old_enabled'] ?? null) === null ? null : $this->booleanFromDatabase('change', 'old_enabled', $row['old_enabled']),
                $this->booleanFromDatabase('change', 'new_enabled', $row['new_enabled']),
                (string) $row['reason'],
                (string) $row['origin'],
                $this->fromText($row['changed_at'], 'changed_at') ?? throw new FeatureFlagStoreException('A history row has no changed_at.'),
                self::nullableText($row['changed_by'] ?? null),
                $subjectKey,
                $this->changeKindFromDatabase($row['change_kind'] ?? null, $subjectKey),
                self::nullableText($row['detail'] ?? null)
            );
        }

        return $rows;
    }

    /** {@inheritdoc} */
    public function getTransactionManager(): ITransactionManager
    {
        return $this->transactions;
    }

    /**
     * Resolves the column map: defaults, then the caller's entries, validated.
     *
     * @param array<string, mixed> $columns
     * @return array{flag: array<string, string|null>, change: array<string, string|null>, subject: array<string, string|null>}
     */
    private function resolveColumns(array $columns): array
    {
        $resolved = [
            'flag' => array_merge(
                array_combine(self::FLAG_COLUMNS, self::FLAG_COLUMNS),
                array_fill_keys([...self::FLAG_OPTIONAL_COLUMNS, ...self::FLAG_COLUMNS_SINCE_2_3], null)
            ),
            'change' => array_merge(
                array_combine(self::CHANGE_COLUMNS, self::CHANGE_COLUMNS),
                array_fill_keys(self::CHANGE_COLUMNS_SINCE_2_3, null)
            ),
            'subject' => array_combine(self::SUBJECT_COLUMNS, self::SUBJECT_COLUMNS),
        ];
        $known = self::canonicalColumns();

        foreach ($columns as $role => $map) {
            if (!isset($resolved[$role])) {
                throw new InvalidArgumentException(sprintf(
                    'Unknown feature flag column role "%s". Expected: flag, change, subject.',
                    (string) $role
                ));
            }
            if (!is_array($map)) {
                throw new InvalidArgumentException(sprintf('The columns of role "%s" must be an array (canonical => real).', $role));
            }
            foreach ($map as $canonical => $real) {
                if (!is_string($canonical) || !in_array($canonical, $known[$role], true)) {
                    throw new InvalidArgumentException(sprintf(
                        'Unknown feature flag column "%s" (role %s). Expected one of: %s.',
                        (string) $canonical,
                        $role,
                        implode(', ', $known[$role])
                    ));
                }
                if ($real === null) {
                    if (in_array($canonical, self::REQUIRED_COLUMNS[$role], true)) {
                        throw new InvalidArgumentException(sprintf('Feature flag column "%s" (role %s) is required and cannot be absent.', $canonical, $role));
                    }
                } elseif (!is_string($real) || preg_match(self::IDENTIFIER, $real) !== 1) {
                    throw new InvalidArgumentException(sprintf(
                        'Feature flag column "%s" (canonical %s, role %s) is not a plain SQL identifier.',
                        is_string($real) ? $real : get_debug_type($real),
                        $canonical,
                        $role
                    ));
                }
                $resolved[$role][$canonical] = $real;
            }
        }

        return $resolved;
    }

    /**
     * @param BooleanStorage|array<int, mixed>|mixed $spec
     * @return array{BooleanStorage, string, string}
     */
    private static function resolveBoolean(string $role, mixed $spec): array
    {
        if ($spec instanceof BooleanStorage) {
            return [$spec, 'Y', 'N'];
        }
        if (is_array($spec) && array_is_list($spec) && count($spec) === 2
            && is_string($spec[0]) && is_string($spec[1]) && $spec[0] !== '' && $spec[1] !== ''
            && strcasecmp($spec[0], $spec[1]) !== 0) {
            return [BooleanStorage::Char, $spec[0], $spec[1]];
        }

        throw new InvalidArgumentException(sprintf(
            'Boolean storage of role "%s" must be a BooleanStorage case or a pair of distinct texts [true, false].',
            $role
        ));
    }

    /** SELECT of the flag rows, with their subjects when the store keeps lists. */
    private function selectFlags(bool $one): string
    {
        $flag = $this->columns['flag'];
        $select = ['f.' . $flag['code'] . ' AS code', 'f.' . $flag['enabled'] . ' AS enabled'];
        foreach (self::FLAG_READ as $canonical) {
            if ($flag[$canonical] !== null) {
                $select[] = 'f.' . $flag[$canonical] . ' AS ' . $canonical;
            }
        }
        $join = '';
        $order = ['f.' . $flag['code']];
        if ($this->tables['subject'] !== null) {
            $subject = $this->columns['subject'];
            $select[] = 's.' . $subject['subject_key'] . ' AS s_subject_key';
            $join = sprintf(' LEFT JOIN %s s ON s.%s = f.%s', $this->tables['subject'], $subject['flag_code'], $flag['code']);
            $order[] = 's.' . $subject['subject_key'];
        }
        $where = [];
        if ($one) {
            $where[] = 'f.' . $flag['code'] . ' = :code';
        }
        if ($flag['deleted_at'] !== null) {
            $where[] = 'f.' . $flag['deleted_at'] . ' IS NULL';
        }

        return sprintf(
            'SELECT %s FROM %s f%s%s ORDER BY %s',
            implode(', ', $select),
            $this->tables['flag'],
            $join,
            $where === [] ? '' : ' WHERE ' . implode(' AND ', $where),
            implode(', ', $order)
        );
    }

    /**
     * Groups the joined rows by flag code.
     *
     * @param list<array<string, mixed>> $rows
     * @return array<string, list<array<string, mixed>>>
     */
    private function groupRows(array $rows): array
    {
        $grouped = [];
        foreach ($rows as $row) {
            $grouped[(string) $row['code']][] = $row;
        }

        return $grouped;
    }

    /**
     * One state from the rows of one flag (one row per subject).
     *
     * @param non-empty-list<array<string, mixed>> $rows
     * @throws FeatureFlagStoreException When a stored value cannot be read
     */
    private function hydrateState(array $rows): FeatureFlagState
    {
        $row = $rows[0];
        $subjects = [];
        foreach ($rows as $joined) {
            if (($joined['s_subject_key'] ?? null) !== null) {
                $subjects[] = (string) $joined['s_subject_key'];
            }
        }

        return new FeatureFlagState(
            (string) $row['code'],
            $this->booleanFromDatabase('flag', 'enabled', $row['enabled']),
            self::nullableText($row['name'] ?? null),
            self::nullableText($row['description'] ?? null),
            self::nullableText($row['category'] ?? null),
            self::nullableText($row['audience'] ?? null),
            self::nullableText($row['notes'] ?? null),
            $this->fromText($row['valid_from'] ?? null, 'valid_from', false),
            $this->fromText($row['valid_until'] ?? null, 'valid_until', true),
            $this->fromText($row['enabled_at'] ?? null, 'enabled_at'),
            self::nullableText($row['enabled_by'] ?? null),
            $this->fromText($row['disabled_at'] ?? null, 'disabled_at'),
            self::nullableText($row['disabled_by'] ?? null),
            ($row['version'] ?? null) === null ? null : (int) $row['version'],
            $subjects,
            $this->rolloutFromDatabase($row['rollout_percent'] ?? null)
        );
    }

    /**
     * The rollout percentage read from its column: null, or an integer from 0 to 100.
     *
     * @throws FeatureFlagStoreException When the column holds anything else
     */
    private function rolloutFromDatabase(mixed $raw): ?int
    {
        if ($raw === null) {
            return null;
        }
        $text = trim((string) $raw);
        if (preg_match('/^\d{1,3}$/', $text) !== 1 || (int) $text > 100) {
            throw new FeatureFlagStoreException(sprintf(
                'Column %s (rollout_percent) holds %s; expected an integer from 0 to 100, or NULL.',
                (string) $this->columns['flag']['rollout_percent'],
                is_scalar($raw) ? var_export($raw, true) : get_debug_type($raw)
            ));
        }

        return (int) $text;
    }

    /**
     * The kind of a history row: the stored one (any case, surrounding spaces ignored), or the one
     * implied by the subject key when the table has no kind column or the row has none. A row with a
     * subject key stored as `toggle` (the default of the column, a 2.1.0 row after the migration) is a
     * Subject change.
     *
     * @throws FeatureFlagStoreException When the stored kind is unknown, or a Subject row has no subject key
     */
    private function changeKindFromDatabase(mixed $raw, ?string $subjectKey): FeatureFlagChangeKind
    {
        $text = $raw === null ? '' : strtolower(trim((string) $raw));
        $kind = $text === '' ? FeatureFlagChangeKind::Toggle : FeatureFlagChangeKind::tryFrom($text);
        if ($kind === null) {
            throw new FeatureFlagStoreException(sprintf(
                "Column %s (change_kind) holds %s; expected one of: %s.",
                (string) $this->columns['change']['change_kind'],
                is_scalar($raw) ? var_export($raw, true) : get_debug_type($raw),
                implode(', ', array_map(static fn(FeatureFlagChangeKind $case): string => $case->value, FeatureFlagChangeKind::cases()))
            ));
        }
        if ($subjectKey !== null && $kind === FeatureFlagChangeKind::Toggle) {
            return FeatureFlagChangeKind::Subject;
        }
        if (($kind === FeatureFlagChangeKind::Subject) !== ($subjectKey !== null)) {
            throw new FeatureFlagStoreException(sprintf(
                "A history row of kind '%s' %s a subject key.",
                $kind->value,
                $subjectKey === null ? 'needs' : 'cannot carry'
            ));
        }

        return $kind;
    }

    /**
     * The canonical flag columns, among $canonical, that the table does not have.
     *
     * @param list<string> $canonical
     * @return list<string>
     */
    private function absentFlagColumns(array $canonical): array
    {
        return array_values(array_filter($canonical, fn(string $column): bool => $this->columns['flag'][$column] === null));
    }

    /**
     * @param list<string> $canonical
     * @throws FeatureFlagStoreException When the flag table lacks one of the columns
     */
    private function assertFlagColumns(string $feature, array $canonical): void
    {
        $absent = $this->absentFlagColumns($canonical);
        if ($absent !== []) {
            throw new FeatureFlagStoreException(sprintf(
                'This feature flag store keeps no %s: the flag table %s has no %s column (mapped to null).',
                $feature,
                $this->tables['flag'],
                implode(', ', $absent)
            ));
        }
    }

    /**
     * Compare-and-set by the optimistic version: writes the values (canonical column => value), increments
     * the version and stamps the update, only when the stored version is the expected one.
     *
     * @param array<string, string|int|null> $values
     */
    private function compareAndSetVersion(string $code, int $expectedVersion, array $values, DateTimeImmutable $at, string|int|null $actor): bool
    {
        $flag = $this->columns['flag'];
        $now = $this->toText($at);
        $set = [];
        $params = [];
        foreach ($values + ['updated_at' => $now, 'updated_by' => $actor] as $canonical => $value) {
            if ($flag[$canonical] !== null) {
                $set[] = $flag[$canonical] . ' = :s_' . $canonical;
                $params[':s_' . $canonical] = $value;
            }
        }
        $set[] = sprintf('%1$s = %1$s + 1', (string) $flag['version']);

        $where = [$flag['code'] . ' = :code', $flag['version'] . ' = :expected_version'];
        $params[':code'] = $code;
        $params[':expected_version'] = $expectedVersion;
        if ($flag['deleted_at'] !== null) {
            $where[] = $flag['deleted_at'] . ' IS NULL';
        }

        return $this->execute(sprintf(
            'UPDATE %s SET %s WHERE %s',
            $this->tables['flag'],
            implode(', ', $set),
            implode(' AND ', $where)
        ), $params)->rowCount() === 1;
    }

    /**
     * True when the flag has a row (deleted or not: the key of the table counts them all).
     */
    private function rowExists(string $code, bool $forUpdate): bool
    {
        return $this->fetchAll(sprintf(
            'SELECT %1$s FROM %2$s WHERE %1$s = :code%3$s',
            $this->columns['flag']['code'],
            $this->tables['flag'],
            $forUpdate && $this->driver === 'mysql' && $this->pdo->inTransaction() ? ' FOR UPDATE' : ''
        ), [':code' => $code]) !== [];
    }

    private function subjectExists(string $code, string $subjectKey, bool $forUpdate): bool
    {
        $subject = $this->columns['subject'];

        return $this->fetchAll(sprintf(
            'SELECT %2$s FROM %1$s WHERE %2$s = :code AND %3$s = :subject_key%4$s',
            $this->subjectTable(),
            $subject['flag_code'],
            $subject['subject_key'],
            $forUpdate && $this->driver === 'mysql' && $this->pdo->inTransaction() ? ' FOR UPDATE' : ''
        ), [':code' => $code, ':subject_key' => $subjectKey]) !== [];
    }

    /**
     * Runs an INSERT that another writer may have raced: when the key rejects it and $exists confirms
     * the row is there now, returns false; any other failure propagates. On PostgreSQL inside a
     * transaction the INSERT runs under a savepoint, so a rejected INSERT leaves the transaction usable.
     *
     * @param array<string, mixed> $params
     * @param \Closure(): bool $exists
     */
    private function insertUnlessRaced(string $sql, array $params, \Closure $exists): bool
    {
        $savepoint = $this->driver === 'pgsql' && $this->pdo->inTransaction();
        if ($savepoint) {
            $this->execute('SAVEPOINT ' . self::SAVEPOINT);
        }
        try {
            $this->execute($sql, $params);
        } catch (FeatureFlagStoreException $e) {
            if ($savepoint) {
                $this->execute('ROLLBACK TO SAVEPOINT ' . self::SAVEPOINT);
            }
            if ($e->isIntegrityViolation() && $exists()) {
                return false;
            }
            throw $e;
        }
        if ($savepoint) {
            $this->execute('RELEASE SAVEPOINT ' . self::SAVEPOINT);
        }

        return true;
    }

    /**
     * @throws FeatureFlagStoreException When the store keeps no subject lists
     */
    private function subjectTable(): string
    {
        return $this->tables['subject']
            ?? throw new FeatureFlagStoreException('This feature flag store has no subject table: subject lists are not kept.');
    }

    /** Value written for a boolean of a role. */
    private function booleanToDatabase(string $role, bool $value): bool|int|string
    {
        [$storage, $true, $false] = $this->booleans[$role];

        return match ($storage) {
            BooleanStorage::Char => $value ? $true : $false,
            BooleanStorage::Integer => $value ? 1 : 0,
            BooleanStorage::Native => $this->driver === 'pgsql' ? $value : ($value ? 1 : 0),
        };
    }

    /**
     * Predicate "column holds $value" for a boolean of a role (a Char column matches every case form
     * of its text, as a read accepts them).
     *
     * @param array<string, mixed> $params Bound parameters, extended in place
     */
    private function booleanPredicate(string $role, string $column, bool $value, string $name, array &$params): string
    {
        [$storage, $true, $false] = $this->booleans[$role];
        if ($storage !== BooleanStorage::Char) {
            $params[':' . $name] = $this->booleanToDatabase($role, $value);

            return $column . ' = :' . $name;
        }
        $text = $value ? $true : $false;
        $forms = array_values(array_unique([$text, strtoupper($text), strtolower($text), ucfirst(strtolower($text))]));
        $placeholders = [];
        foreach ($forms as $i => $form) {
            $params[':' . $name . '_' . $i] = $form;
            $placeholders[] = ':' . $name . '_' . $i;
        }

        return sprintf('%s IN (%s)', $column, implode(', ', $placeholders));
    }

    /**
     * Boolean read from a column of a role: strict for Char (the two texts, any case, trailing spaces of
     * a CHAR column ignored), lenient otherwise (true/false, t/f, 1/0, y/n, yes/no, on/off).
     *
     * @throws FeatureFlagStoreException When a Char column holds another value
     */
    private function booleanFromDatabase(string $role, string $canonical, mixed $raw): bool
    {
        [$storage, $true, $false] = $this->booleans[$role];
        if ($storage === BooleanStorage::Char) {
            if (is_string($raw) || is_int($raw)) {
                $text = rtrim((string) $raw, ' ');
                if (strcasecmp($text, $true) === 0) {
                    return true;
                }
                if (strcasecmp($text, $false) === 0) {
                    return false;
                }
            }
            throw new FeatureFlagStoreException(sprintf(
                "Column %s (%s) holds %s; expected '%s' (true) or '%s' (false).",
                (string) $this->columns[$role][$canonical],
                $canonical,
                is_scalar($raw) ? var_export($raw, true) : get_debug_type($raw),
                $true,
                $false
            ));
        }
        if (is_bool($raw)) {
            return $raw;
        }
        if (is_int($raw) || is_float($raw)) {
            return $raw != 0;
        }

        return in_array(strtolower(trim((string) $raw)), ['1', 't', 'true', 'y', 'yes', 'on'], true);
    }

    /** An instant as written: in the store's zone and format. */
    private function toText(DateTimeImmutable $at): string
    {
        return $at->setTimezone($this->zone)->format($this->timestampFormat);
    }

    /**
     * An instant read from text, in the store's zone; a date only is the first instant of the day, or the
     * last one when $endOfDay is true (an inclusive upper bound).
     *
     * @throws FeatureFlagStoreException When the text is not a date
     */
    private function fromText(mixed $raw, string $canonical, bool $endOfDay = false): ?DateTimeImmutable
    {
        if ($raw === null) {
            return null;
        }
        $text = trim((string) $raw);
        if ($text === '') {
            return null;
        }
        try {
            $instant = new DateTimeImmutable($text, $this->zone);
        } catch (Exception $e) {
            throw new FeatureFlagStoreException(sprintf('Column %s holds "%s", which is not a date.', $canonical, $text), $e);
        }
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $text) === 1) {
            $instant = $endOfDay ? $instant->setTime(23, 59, 59, 999999) : $instant->setTime(0, 0);
        }

        return $instant;
    }

    private static function nullableText(mixed $value): ?string
    {
        return $value === null ? null : (string) $value;
    }

    /**
     * @param array<string, mixed> $params
     * @return list<array<string, mixed>>
     */
    private function fetchAll(string $sql, array $params): array
    {
        $statement = $this->execute($sql, $params);
        try {
            $rows = $statement->fetchAll(PDO::FETCH_ASSOC);
        } catch (PDOException $e) {
            throw $this->wrap($e);
        }
        $statement->closeCursor();

        return array_map(static fn(array $row): array => array_change_key_case($row, CASE_LOWER), $rows);
    }

    /**
     * Prepares, binds and executes one statement, and logs it.
     *
     * @param array<string, mixed> $params
     * @throws FeatureFlagStoreException
     */
    private function execute(string $sql, array $params = []): PDOStatement
    {
        $started = hrtime(true);
        try {
            $statement = $this->pdo->prepare($sql);
            if (!$statement instanceof PDOStatement) {
                throw $this->driverError($this->pdo->errorInfo());
            }
            foreach ($params as $name => $value) {
                $statement->bindValue($name, $value, match (true) {
                    $value === null => PDO::PARAM_NULL,
                    is_bool($value) => PDO::PARAM_BOOL,
                    is_int($value) => PDO::PARAM_INT,
                    default => PDO::PARAM_STR,
                });
            }
            if (!$statement->execute()) {
                throw $this->driverError($statement->errorInfo());
            }
        } catch (PDOException $e) {
            throw $this->wrap($e);
        } finally {
            $this->log($sql, $params, $started);
        }

        return $statement;
    }

    /**
     * @param array<string, mixed> $params
     */
    private function log(string $sql, array $params, int $started): void
    {
        if ($this->logger === null) {
            return;
        }
        try {
            $this->logger->log($sql, count($params), (hrtime(true) - $started) / 1e6, $this->logParameters ? $params : null);
        } catch (Throwable) {
            // A broken log never changes the outcome of a statement
        }
    }

    private function wrap(PDOException $e): FeatureFlagStoreException
    {
        $info = $e->errorInfo;

        return new FeatureFlagStoreException(
            'Feature flag statement failed: ' . $e->getMessage(),
            $e,
            is_array($info) && isset($info[0]) ? (string) $info[0] : (is_string($e->getCode()) ? $e->getCode() : null)
        );
    }

    /**
     * @param array<int, mixed> $errorInfo PDO errorInfo() triple
     */
    private function driverError(array $errorInfo): FeatureFlagStoreException
    {
        return new FeatureFlagStoreException(
            sprintf('Feature flag statement failed: [%s] %s', (string) ($errorInfo[0] ?? ''), (string) ($errorInfo[2] ?? 'unknown driver error')),
            null,
            isset($errorInfo[0]) ? (string) $errorInfo[0] : null
        );
    }
